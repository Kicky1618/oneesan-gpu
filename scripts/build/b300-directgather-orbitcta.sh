#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"

N="${N:-27}"; W=$((N + 1)); ARCH="${ARCH:-native}"
LOW_LUT_K="${LOW_LUT_K:-$((W / 2))}"; HIGH_LUT_K=$((W - LOW_LUT_K - 1))
OUT="${OUT:-oneesan_cuda_gridfp_b300_directgather_orbitcta_n${N}}"
PM_ACCUM="${PM_ACCUM:-0}"; WINDOW4="${RANKFORMULA_MLP_WINDOW4:-0}"
DIRECTGATHER64="${DIRECTGATHER64:-1}"
DIRECTGATHER_SPARSE64="${DIRECTGATHER_SPARSE64:-0}"
DIRECTGATHER_SORT_RANKS="${DIRECTGATHER_SORT_RANKS:-0}"
PAIR_MLP="${PAIR_MLP:-0}"; CPASYNC_PAIR="${CPASYNC_PAIR:-0}"
QUAD_MLP="${QUAD_MLP:-0}"; QUAD_OVERLAP_LOCAL="${QUAD_OVERLAP_LOCAL:-0}"; QUAD_LOCAL_DIRECT_MAX="${QUAD_LOCAL_DIRECT_MAX:-0}"; QUAD_SPARSE_DESC_MLP="${QUAD_SPARSE_DESC_MLP:-0}"
PRECTX_FORWARD="${PRECTX_FORWARD:-0}"; PRECTX_REVERSE="${PRECTX_REVERSE:-0}"
PRECTX_COMPACT="${PRECTX_COMPACT:-0}"; PRECTX_FLAT_BID="${PRECTX_FLAT_BID:-0}"; PRECTX_FLAT_BID_FUSED="${PRECTX_FLAT_BID_FUSED:-0}"
ORBITCTA_FLAT="${ORBITCTA_FLAT:-0}"; ORBITCTA_FLAT_CHUNK="${ORBITCTA_FLAT_CHUNK:-1}"
ORBITCTA_COL_ILP="${ORBITCTA_COL_ILP:-1}"
FORCE7="${RANKFORMULA_DIRECTGATHER_FORCE7:-0}"; PTXAS_VERBOSE="${PTXAS_VERBOSE:-1}"
for x in WINDOW4 DIRECTGATHER64 DIRECTGATHER_SPARSE64 DIRECTGATHER_SORT_RANKS PAIR_MLP CPASYNC_PAIR QUAD_MLP QUAD_OVERLAP_LOCAL QUAD_SPARSE_DESC_MLP PRECTX_FORWARD PRECTX_REVERSE PRECTX_COMPACT PRECTX_FLAT_BID PRECTX_FLAT_BID_FUSED ORBITCTA_FLAT FORCE7 PM_ACCUM PTXAS_VERBOSE; do
  v="${!x}"; [[ "$v" == 0 || "$v" == 1 ]] || { echo "$x must be 0 or 1" >&2; exit 2; }
done
[[ "$QUAD_LOCAL_DIRECT_MAX" =~ ^[0-9]+$ ]] && (( QUAD_LOCAL_DIRECT_MAX <= 8 )) || { echo "QUAD_LOCAL_DIRECT_MAX must be 0..8" >&2; exit 2; }
case "$ORBITCTA_COL_ILP" in 1|2|4) ;; *) echo "ORBITCTA_COL_ILP must be 1, 2, or 4" >&2; exit 2;; esac
case "$ORBITCTA_FLAT_CHUNK" in 1|2|4|8|16|32) ;; *) echo "ORBITCTA_FLAT_CHUNK must be 1, 2, 4, 8, 16, or 32" >&2; exit 2;; esac
[[ "$ORBITCTA_FLAT" == 1 || "$ORBITCTA_FLAT_CHUNK" == 1 ]] || { echo "ORBITCTA_FLAT_CHUNK>1 requires ORBITCTA_FLAT=1" >&2; exit 2; }
if [[ "$PRECTX_FLAT_BID" == 1 ]]; then
  [[ "$ORBITCTA_FLAT" == 1 ]] || { echo "PRECTX_FLAT_BID requires ORBITCTA_FLAT=1" >&2; exit 2; }
  [[ "$PRECTX_COMPACT" == 1 && "$PRECTX_FORWARD" == 1 && "$PRECTX_REVERSE" == 1 ]] || {
    echo "PRECTX_FLAT_BID requires PRECTX_COMPACT=1 PRECTX_FORWARD=1 PRECTX_REVERSE=1" >&2; exit 2;
  }
  [[ "$ORBITCTA_FLAT_CHUNK" == 1 ]] || { echo "PRECTX_FLAT_BID is isolated from FLAT_CHUNK>1" >&2; exit 2; }
fi
[[ "$PRECTX_FLAT_BID_FUSED" == 0 || "$PRECTX_FLAT_BID" == 1 ]] || { echo "PRECTX_FLAT_BID_FUSED requires PRECTX_FLAT_BID=1" >&2; exit 2; }
[[ "$FORCE7" == 0 || "$WINDOW4" == 0 ]] || { echo "FORCE7 and WINDOW4 are isolated" >&2; exit 2; }
[[ "$DIRECTGATHER64" == 0 || "$FORCE7" == 0 ]] || { echo "DIRECTGATHER64 does not use FORCE7" >&2; exit 2; }
[[ "$DIRECTGATHER_SPARSE64" == 0 || "$DIRECTGATHER64" == 1 ]] || { echo "DIRECTGATHER_SPARSE64 requires DIRECTGATHER64=1" >&2; exit 2; }
[[ "$DIRECTGATHER_SORT_RANKS" == 0 || "$DIRECTGATHER64" == 1 ]] || { echo "DIRECTGATHER_SORT_RANKS requires DIRECTGATHER64=1" >&2; exit 2; }
[[ "$DIRECTGATHER_SORT_RANKS" == 0 || "$DIRECTGATHER_SPARSE64" == 0 ]] || { echo "DIRECTGATHER_SORT_RANKS currently targets dense DIRECTGATHER64 only" >&2; exit 2; }
if [[ "$PRECTX_COMPACT" == 1 ]]; then
  [[ "$PRECTX_FORWARD" == 1 || "$PRECTX_REVERSE" == 1 ]] || {
    echo "PRECTX_COMPACT requires PRECTX_FORWARD=1 and/or PRECTX_REVERSE=1" >&2; exit 2;
  }
fi
if [[ "$PAIR_MLP" == 1 ]]; then
  [[ "$WINDOW4" == 1 ]] || { echo "PAIR_MLP requires RANKFORMULA_MLP_WINDOW4=1" >&2; exit 2; }
  [[ "$ORBITCTA_COL_ILP" == 2 || "$ORBITCTA_COL_ILP" == 4 ]] || { echo "PAIR_MLP requires ORBITCTA_COL_ILP=2 or 4" >&2; exit 2; }
fi
if [[ "$CPASYNC_PAIR" == 1 ]]; then
  [[ "$PAIR_MLP" == 1 ]] || { echo "CPASYNC_PAIR requires PAIR_MLP=1" >&2; exit 2; }
  [[ "$WINDOW4" == 1 ]] || { echo "CPASYNC_PAIR requires RANKFORMULA_MLP_WINDOW4=1" >&2; exit 2; }
fi
if [[ "$QUAD_MLP" == 1 ]]; then
  [[ "$ORBITCTA_FLAT" == 1 ]] || { echo "QUAD_MLP currently targets flat orbit CTA" >&2; exit 2; }
  (( ORBITCTA_FLAT_CHUNK > 1 )) || { echo "QUAD_MLP currently targets chunked flat scheduler (FLAT_CHUNK>1)" >&2; exit 2; }
  [[ "$ORBITCTA_COL_ILP" == 4 ]] || { echo "QUAD_MLP requires ORBITCTA_COL_ILP=4" >&2; exit 2; }
  [[ "$PAIR_MLP" == 1 ]] || { echo "QUAD_MLP requires PAIR_MLP=1 for tail fallback" >&2; exit 2; }
  [[ "$WINDOW4" == 1 ]] || { echo "QUAD_MLP requires WINDOW4=1" >&2; exit 2; }
  [[ "$DIRECTGATHER64" == 1 ]] || { echo "QUAD_MLP requires DIRECTGATHER64=1" >&2; exit 2; }
else
  [[ "$QUAD_OVERLAP_LOCAL" == 0 ]] || { echo "QUAD_OVERLAP_LOCAL requires QUAD_MLP=1" >&2; exit 2; }
  (( QUAD_LOCAL_DIRECT_MAX == 0 )) || { echo "QUAD_LOCAL_DIRECT_MAX requires QUAD_MLP=1" >&2; exit 2; }
fi
if [[ "$QUAD_OVERLAP_LOCAL" == 1 ]]; then
  [[ "$CPASYNC_PAIR" == 1 ]] || { echo "QUAD_OVERLAP_LOCAL requires CPASYNC_PAIR=1" >&2; exit 2; }
  (( QUAD_LOCAL_DIRECT_MAX == 0 )) || { echo "QUAD_OVERLAP_LOCAL uses direct local loads; set QUAD_LOCAL_DIRECT_MAX=0" >&2; exit 2; }
fi
if [[ "$QUAD_SPARSE_DESC_MLP" == 1 ]]; then
  [[ "$QUAD_MLP" == 1 && "$QUAD_OVERLAP_LOCAL" == 1 ]] || { echo "QUAD_SPARSE_DESC_MLP requires QUAD_MLP=1 and QUAD_OVERLAP_LOCAL=1" >&2; exit 2; }
  [[ "$DIRECTGATHER_SPARSE64" == 1 ]] || { echo "QUAD_SPARSE_DESC_MLP requires DIRECTGATHER_SPARSE64=1" >&2; exit 2; }
fi

if [[ "$ORBITCTA_FLAT" == 1 ]]; then
  SRC="$(repo_path src/cuda/b300/oneesan_cuda_gridfp_b300_bucket_snake_onepass_pattern10_depthcode_orbitcta_flat_directgather_graph_batch_pipeline.cu)"
  BACKEND_TAG="orbitcta-flat-directgather"
else
  SRC="$(repo_path src/cuda/b300/oneesan_cuda_gridfp_b300_bucket_snake_onepass_pattern10_depthcode_orbitcta_directgather_graph_batch_pipeline.cu)"
  BACKEND_TAG="orbitcta-directgather"
fi
BIN="$(build_path "$OUT")"
NVCC_EXTRA=(); [[ "$PTXAS_VERBOSE" == 1 ]] && NVCC_EXTRA+=("-Xptxas=-v")

TMPDIR="$ONEESAN_TMP_DIR" nvcc -O3 -std=c++17 -lineinfo -arch="$ARCH" \
  "${NVCC_EXTRA[@]}" \
  -DTARGET_W="$W" -DLOW_LUT_K="$LOW_LUT_K" -DHIGH_LUT_K="$HIGH_LUT_K" \
  -DGPU_DIRECT_PM_ACCUM="$PM_ACCUM" -DBKCZ_TERNARY_KEY4=1 \
  -DP10DC_DECODE_LDG=1 -DP10DC_RANKSTREAM_LUT_LDG=1 -DP10DC_RANKSTREAM_LUT_PAD256=0 \
  -DP10DC_RANKFORMULA_NOMETA_BLOCK=16 \
  -DP10DC_RANKFORMULA_NOMETA_WARPSHARE=1 \
  -DP10DC_RANKFORMULA_NOMETA_COOPGROUP=1 \
  -DP10DC_RANKFORMULA_NOMETA_COOP_UNROLL=0 \
  -DP10DC_RANKFORMULA_NOMETA_GROUP56=0 -DP10DC_RANKFORMULA_NOMETA_GROUP61=1 \
  -DP10DC_RANKFORMULA_NOMETA_DIRECTMAP=1 \
  -DP10DC_RANKFORMULA_DIRECTGATHER=1 \
  -DP10DC_RANKFORMULA_DIRECTGATHER_DEPTHMAJOR=1 \
  -DP10DC_RANKFORMULA_DIRECTGATHER64="$DIRECTGATHER64" \
  -DP10DC_RANKFORMULA_DIRECTGATHER_SPARSE64="$DIRECTGATHER_SPARSE64" \
  -DP10DC_RANKFORMULA_DIRECTGATHER_SORT_RANKS="$DIRECTGATHER_SORT_RANKS" \
  -DP10DC_RANKFORMULA_DIRECTGATHER_FORCE7="$FORCE7" \
  -DP10DC_RANKFORMULA_MLP_WINDOW4="$WINDOW4" \
  -DP10DC_RANKFORMULA_PREFETCH_NEXT=0 -DP10DC_RANKFORMULA_PAIR_MLP="$PAIR_MLP" \
  -DP10DC_RANKFORMULA_CPASYNC_PAIR="$CPASYNC_PAIR" \
  -DP10DC_RANKFORMULA_QUAD_MLP="$QUAD_MLP" \
  -DP10DC_RANKFORMULA_QUAD_OVERLAP_LOCAL="$QUAD_OVERLAP_LOCAL" \
  -DP10DC_RANKFORMULA_QUAD_LOCAL_DIRECT_MAX="$QUAD_LOCAL_DIRECT_MAX" \
  -DP10DC_RANKFORMULA_QUAD_SPARSE_DESC_MLP="$QUAD_SPARSE_DESC_MLP" \
  -DP10DC_RANKFORMULA_PRECTX_FORWARD="$PRECTX_FORWARD" \
  -DP10DC_RANKFORMULA_PRECTX_REVERSE="$PRECTX_REVERSE" \
  -DP10DC_RANKFORMULA_PRECTX_COMPACT="$PRECTX_COMPACT" \
  -DP10DC_RANKFORMULA_PRECTX_FLAT_BID="$PRECTX_FLAT_BID" \
  -DP10DC_RANKFORMULA_PRECTX_FLAT_BID_FUSED="$PRECTX_FLAT_BID_FUSED" \
  -DP10DC_ORBITCTA_FLAT_CHUNK="$ORBITCTA_FLAT_CHUNK" \
  -DP10DC_WARPSTRIPED_COL_ILP="$ORBITCTA_COL_ILP" \
  -DP10DC_ORBITCTA_COL_ILP="$ORBITCTA_COL_ILP" \
  -DP10DC_RANKFORMULA_ABSTRACT_SELECT8=1 \
  -DP10DC_RANKFORMULA_ABSTRACT_DEPTH4=1 \
  -DP10DC_RANKFORMULA_ABSTRACT_SRCPACK10=1 \
  -DP10DC_RANKFORMULA_GATHER_MLP=1 \
  -DP10DC_RANKCHUNK32_ONESHFL=1 -DP10DC_RANKCHUNK32_FUSED16=0 \
  -DP10DC_RANKCHUNK32_BYTEPACK=0 -DP10DC_RANKCHUNK32_ALIGN32=0 \
  -DP10DC_RANKCHUNK32_BLOCK64=0 -DP10DC_RANKDELTA8_FUSED13=1 \
  -DP10DC_RANKFORMULA_SPARSE_BASE=1 -DP10DC_RANKFORMULA_RAWCODE=1 \
  -DP10DC_RANKFORMULA_INLINE_CROSS=1 -DP10DC_RANKFORMULA_BASE_DELTA=0 \
  -DP10DC_RANKFORMULA_SLOTMETA=0 -DP10DC_RANKFORMULA_SLOTROW32=0 \
  "$SRC" -o "$BIN"

echo "built $BIN backend=$BACKEND_TAG flat=$ORBITCTA_FLAT flat_chunk=$ORBITCTA_FLAT_CHUNK depthmajor=1 directgather64=$DIRECTGATHER64 sparse64=$DIRECTGATHER_SPARSE64 sort_ranks=$DIRECTGATHER_SORT_RANKS pair_mlp=$PAIR_MLP cpasync_pair=$CPASYNC_PAIR quad_mlp=$QUAD_MLP quad_overlap_local=$QUAD_OVERLAP_LOCAL quad_local_direct_max=$QUAD_LOCAL_DIRECT_MAX quad_sparse_desc_mlp=$QUAD_SPARSE_DESC_MLP prectx_forward=$PRECTX_FORWARD prectx_reverse=$PRECTX_REVERSE prectx_compact=$PRECTX_COMPACT prectx_flat_bid=$PRECTX_FLAT_BID prectx_flat_bid_fused=$PRECTX_FLAT_BID_FUSED orbitcta_col_ilp=$ORBITCTA_COL_ILP pm_accum=$PM_ACCUM window4=$WINDOW4 force7=$FORCE7" >&2
if [[ "$ORBITCTA_FLAT" == 1 ]]; then
  echo "run: BUCKET_THREADS=${BUCKET_THREADS:-256} flat_pool=auto-occupancy [BUCKET_ORBITCTA_FLAT_BLOCKS_PER_SM=<tune>] flat_chunk=$ORBITCTA_FLAT_CHUNK prectx_flat_bid=$PRECTX_FLAT_BID fused=$PRECTX_FLAT_BID_FUSED BUCKET_LOW_GRID_X=${BUCKET_LOW_GRID_X:-16} BUCKET_LOW_GRID_Y=${BUCKET_LOW_GRID_Y:-8} $BIN $N <target_mib> <max_window> 8 <mod>" >&2
else
  echo "run: BUCKET_THREADS=${BUCKET_THREADS:-256} BUCKET_ORBITCTA_GRID_Y=${BUCKET_ORBITCTA_GRID_Y:-128} BUCKET_LOW_GRID_X=${BUCKET_LOW_GRID_X:-16} BUCKET_LOW_GRID_Y=${BUCKET_LOW_GRID_Y:-8} $BIN $N <target_mib> <max_window> 8 <mod>" >&2
fi
