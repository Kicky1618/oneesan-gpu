#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"
N="${N:-27}"
[[ "$N" == 27 ]] || { echo "b300-hbm32-vmm-basearg-stagedmeta.sh is specialized for n=27 / W=28" >&2; exit 2; }
W=$((N+1));NVCC="${NVCC:-nvcc}";ARCH="${ARCH:-native}";LOW_LUT_K="${LOW_LUT_K:-13}";HIGH_LUT_K="${HIGH_LUT_K:-13}";B300_STAGED_META_MAX_MIB="${B300_STAGED_META_MAX_MIB:-512}"
SRC="$(repo_path "${SRC:-src/cuda/b300/oneesan_cuda_gridfp_b300_hbm32_fullmate_dropN.cu}")"
GEN="$ONEESAN_ROOT/scripts/build/gen-b300-vmm-production.py"
PRUNE="$ONEESAN_ROOT/scripts/build/prune-b300-vmm-stale-shard-symbols.py"
BASEARG="$ONEESAN_ROOT/scripts/build/lower-b300-vmm-basearg.py"
PACK="$ONEESAN_ROOT/scripts/build/lower-b300-packed-group-meta.py"
STAGE="$ONEESAN_ROOT/scripts/build/lower-b300-staged-group-meta.py"
ROWLIMIT="$ONEESAN_ROOT/scripts/build/lower-b300-row-limit.py"
GENSRC="${GENSRC:-$ONEESAN_BUILD_DIR/generated_b300_hbm32_vmm_basearg_stagedmeta_n${N}.cu}"
OUT="$(build_path "${OUT:-oneesan_cuda_gridfp_b300_hbm32_vmm_basearg_stagedmeta_n${N}}")"
require_nvcc_version_at_least "$NVCC" 13 0 "B300 sm_103/VMM staged group metadata production"
bash "$ONEESAN_ROOT/scripts/bench/b300-vmm-basearg-stagedmeta-production-generate-proof.sh"
python3 "$GEN" "$SRC" "$GENSRC"
python3 "$PRUNE" "$GENSRC" "$GENSRC"
python3 "$BASEARG" "$GENSRC" "$GENSRC"
python3 "$PACK" "$GENSRC" "$GENSRC"
python3 "$STAGE" "$GENSRC" "$GENSRC"
python3 "$ROWLIMIT" "$GENSRC" "$GENSRC"
TMPDIR="$ONEESAN_TMP_DIR" "$NVCC" -O3 -std=c++17 -lineinfo -arch="$ARCH" \
  -I"$ONEESAN_ROOT/src/cuda/b300" -DTARGET_W="$W" -DLOW_LUT_K="$LOW_LUT_K" -DHIGH_LUT_K="$HIGH_LUT_K" \
  "$GENSRC" -lcuda -o "$OUT"
echo "built $OUT"
echo "  generated_source=$GENSRC"
echo "  n=$N width=$W arch=$ARCH low_lut_k=$LOW_LUT_K high_lut_k=$HIGH_LUT_K"
echo "  authoritative_storage=contiguous_multi_gpu_vmm"
echo "  vmm_base_source=kernel_param"
echo "  packed_group_meta=1"
echo "  staged_group_meta=1"
echo "  group_meta_bytes=13936"
echo "  staged_h2d_once=1"
echo "  per_group_meta_copy=D2D_sync"
echo "  host_meta_rebuild_per_group=0"
echo "  staged_meta_max_mib=$B300_STAGED_META_MAX_MIB"
echo "  row_limit_env=B300_ROW_LIMIT default_rows=28"
