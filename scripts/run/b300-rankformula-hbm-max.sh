#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"
N="${N:-27}";TARGET_MIB="${TARGET_MIB:-16384}";MAX_WINDOW="${MAX_WINDOW:-14}";NGPU="${NGPU:-8}";MOD="${MOD:-4294967291}"
THREADS="${BUCKET_THREADS:-256}";GX="${BUCKET_GRID_X:-32}";GY="${BUCKET_GRID_Y:-8}"
COL_ILP="${COL_ILP:-2}";DEPTHMAJOR="${DEPTHMAJOR:-1}";PAIR_MLP="${PAIR_MLP:-1}";CPASYNC_PAIR="${CPASYNC_PAIR:-0}";SORTED="${SORTED:-0}"
PRECTX_FORWARD="${PRECTX_FORWARD:-0}";PRECTX_REVERSE="${PRECTX_REVERSE:-0}"
PREFETCH_NEXT="${PREFETCH_NEXT:-0}";FORCE7="${FORCE7:-0}";MLP_WINDOW4="${MLP_WINDOW4:-1}"
DIRECTGATHER64="${DIRECTGATHER64:-1}";DIRECTGATHER_SPARSE64="${DIRECTGATHER_SPARSE64:-0}"
MAXRREGCOUNT="${MAXRREGCOUNT:-0}"
OUT="${OUT:-$ONEESAN_BUILD_DIR/oneesan_cuda_gridfp_b300_rankformula_hbm_max_n${N}}"
[[ "$NGPU" == 8 ]]||{ echo 'HBM max launcher currently requires NGPU=8' >&2;exit 2; }
if [[ "${BUILD:-1}" == 1 ]];then
  N="$N" OUT="$OUT" COL_ILP="$COL_ILP" DEPTHMAJOR="$DEPTHMAJOR" PAIR_MLP="$PAIR_MLP" CPASYNC_PAIR="$CPASYNC_PAIR" SORTED="$SORTED" \
  PRECTX_FORWARD="$PRECTX_FORWARD" PRECTX_REVERSE="$PRECTX_REVERSE" DIRECTGATHER64="$DIRECTGATHER64" DIRECTGATHER_SPARSE64="$DIRECTGATHER_SPARSE64" \
  PREFETCH_NEXT="$PREFETCH_NEXT" FORCE7="$FORCE7" MLP_WINDOW4="$MLP_WINDOW4" MAXRREGCOUNT="$MAXRREGCOUNT" \
  bash "$ONEESAN_ROOT/scripts/build/b300-rankformula-hbm-max.sh"
fi
[[ -x "$OUT" ]]||{ echo "missing binary $OUT" >&2;exit 3; }
echo "run HBM-max n=$N threads=$THREADS gx=$GX gy=$GY col_ilp=$COL_ILP depthmajor=$DEPTHMAJOR pair_mlp=$PAIR_MLP cpasync_pair=$CPASYNC_PAIR directgather64=$DIRECTGATHER64 sparse64=$DIRECTGATHER_SPARSE64 sorted=$SORTED prectx_forward=$PRECTX_FORWARD prectx_reverse=$PRECTX_REVERSE window4=$MLP_WINDOW4 prefetch=$PREFETCH_NEXT force7=$FORCE7 maxrregcount=$MAXRREGCOUNT" >&2
BUCKET_THREADS="$THREADS" BUCKET_GRID_X="$GX" BUCKET_GRID_Y="$GY" "$OUT" "$N" "$TARGET_MIB" "$MAX_WINDOW" "$NGPU" "$MOD"
