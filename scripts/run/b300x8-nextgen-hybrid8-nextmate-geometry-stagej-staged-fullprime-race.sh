#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"

N="${1:-27}"; if (($#>0)); then shift; fi
[[ "$N" == 27 ]] || { echo 'Stage-J independent mate-geometry race targets n=27' >&2; exit 2; }

INPUT_ENV="${INPUT_ENV:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextself_staged_winner.env}"
PROFILE_FILE="${PROFILE_FILE:-$ONEESAN_ROOT/work/b300_hbm_profile_refined21.env}"
ARCH="${ARCH:-native}"
TARGET_MIB="${TARGET_MIB:-65536}"
MAX_WINDOW="${MAX_WINDOW:-14}"
RUN_STAGED="${RUN_STAGED:-1}"
SELECT_ONLY="${SELECT_ONLY:-1}"
REBUILD_BUCKETS="${REBUILD_BUCKETS:-1}"
PREPARE_ONLY="${PREPARE_ONLY:-0}"
MIN_SPEEDUP="${MIN_SPEEDUP:-1.002}"
MATE_WIDTH_LIST="${MATE_WIDTH_LIST:-1 2 4 8}"
MATE_DISTANCE_LIST="${MATE_DISTANCE_LIST:-1 2 4}"
SELF_EVICT="${SELF_EVICT:-default}"
MATE_EVICT="${MATE_EVICT:-default}"
STAGED_PREFIX="${STAGED_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextmate_geometry_stagej_staged}"
WINNER_ENV="${WINNER_ENV:-${STAGED_PREFIX}_winner.env}"
MANIFEST="${MANIFEST:-${WINNER_ENV%.env}_promotion-inputs.sha256}"
RACE_PREFIX="${RACE_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextmate_geometry_stagej_fullprime_n27}"
PREPARE_ENV="${PREPARE_ENV:-${RACE_PREFIX}_prepared.env}"
PROMOTION_ENV="${PROMOTION_ENV:-${RACE_PREFIX}_promotion.env}"
STAGEJ_BUILD_DIR="${STAGEJ_BUILD_DIR:-$ONEESAN_BUILD_DIR/stagej-mate-geometry}"
LEGACY="$ONEESAN_ROOT/scripts/run/b300x8-nextgen-hybrid8-nextmate-geometry-staged-fullprime-race.sh"

for x in RUN_STAGED SELECT_ONLY REBUILD_BUCKETS PREPARE_ONLY; do
  v="${!x}"; [[ "$v" == 0 || "$v" == 1 ]] || { echo "$x must be 0/1" >&2; exit 2; }
done
for x in TARGET_MIB MAX_WINDOW; do v="${!x}"; [[ "$v" =~ ^[1-9][0-9]*$ ]] || exit 2; done
for ev in SELF_EVICT MATE_EVICT; do case "${!ev}" in default|normal|last) ;; *) exit 2;; esac; done
[[ -s "$INPUT_ENV" ]] || { echo "missing Stage-F INPUT_ENV=$INPUT_ENV" >&2; exit 2; }
[[ -s "$PROFILE_FILE" ]] || { echo "missing PROFILE_FILE=$PROFILE_FILE" >&2; exit 2; }
command -v sha256sum >/dev/null || exit 2
mkdir -p "$STAGEJ_BUILD_DIR" "$(dirname "$WINNER_ENV")" "$(dirname "$PREPARE_ENV")" "$(dirname "$MANIFEST")"

# Keep the historical Stage-I geometry implementation in a child process only.
# Its build artifacts are isolated under build/stagej-mate-geometry and its env
# files use private names, so the official Stage-I self-eviction namespace can
# never leak into the caller.
LEGACY_PREFIX="${STAGED_PREFIX}.legacy-stagei"
LEGACY_WINNER="${LEGACY_PREFIX}_winner.env"
LEGACY_RACE_PREFIX="${RACE_PREFIX}.legacy-stagei"
LEGACY_PREPARE="${LEGACY_RACE_PREFIX}_prepared.env"
LEGACY_MANIFEST="${LEGACY_WINNER%.env}_promotion-inputs.sha256"

ONEESAN_BUILD_DIR="$STAGEJ_BUILD_DIR" \
INPUT_ENV="$INPUT_ENV" PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" \
RUN_STAGED="$RUN_STAGED" SELECT_ONLY=1 REBUILD_BUCKETS="$REBUILD_BUCKETS" PREPARE_ONLY=1 MIN_SPEEDUP="$MIN_SPEEDUP" \
MATE_WIDTH_LIST="$MATE_WIDTH_LIST" MATE_DISTANCE_LIST="$MATE_DISTANCE_LIST" SELF_EVICT="$SELF_EVICT" MATE_EVICT="$MATE_EVICT" \
STAGED_PREFIX="$LEGACY_PREFIX" WINNER_ENV="$LEGACY_WINNER" MANIFEST="$LEGACY_MANIFEST" RACE_PREFIX="$LEGACY_RACE_PREFIX" PREPARE_ENV="$LEGACY_PREPARE" \
bash "$LEGACY" 27

[[ -s "$LEGACY_WINNER" && -s "$LEGACY_PREPARE" ]] || { echo 'Stage-J legacy calibration outputs missing' >&2; exit 3; }
# shellcheck disable=SC1090
source "$LEGACY_PREPARE"
for k in \
  B300_STAGEI_PREPARED B300_STAGEI_PREPARED_BIN B300_STAGEI_PREPARED_LABEL B300_STAGEI_PREPARED_THREADS \
  B300_STAGEI_PREPARED_CONTROL_BIN B300_STAGEI_PREPARED_CONTROL_LABEL B300_STAGEI_PREPARED_CONTROL_THREADS \
  B300_STAGEI_PREPARED_SELF_WIDTH B300_STAGEI_PREPARED_SELF_DISTANCE \
  B300_STAGEI_PREPARED_MATE_WIDTH B300_STAGEI_PREPARED_MATE_DISTANCE B300_STAGEI_PREPARED_STAGED_SPEEDUP; do
  [[ -n "${!k+x}" ]] || { echo "Stage-J private prepare missing $k" >&2; exit 3; }
done
[[ "$B300_STAGEI_PREPARED" == 1 ]] || exit 4
[[ -x "$B300_STAGEI_PREPARED_BIN" && -x "$B300_STAGEI_PREPARED_CONTROL_BIN" ]] || exit 3

# Export a collision-free Stage-J winner snapshot. Keep all historical fields
# for auditability, but rename the namespace before it can be sourced upstream.
sed -e 's/B300_STAGEI_/B300_STAGEJ_/g' -e 's/Stage-I/Stage-J/g' -e 's/Stage I/Stage J/g' "$LEGACY_WINNER" >"${WINNER_ENV}.tmp"
mv "${WINNER_ENV}.tmp" "$WINNER_ENV"

FINAL_SHA="$(sha256sum "$B300_STAGEI_PREPARED_BIN" | awk '{print $1}')"
CONTROL_SHA="$(sha256sum "$B300_STAGEI_PREPARED_CONTROL_BIN" | awk '{print $1}')"
INPUT_SHA="$(sha256sum "$INPUT_ENV" | awk '{print $1}')"
WINNER_SHA="$(sha256sum "$WINNER_ENV" | awk '{print $1}')"
{
  sha256sum "$WINNER_ENV" "$INPUT_ENV" "$B300_STAGEI_PREPARED_BIN" "$B300_STAGEI_PREPARED_CONTROL_BIN"
} >"${MANIFEST}.tmp"
mv "${MANIFEST}.tmp" "$MANIFEST"
sha256sum -c "$MANIFEST" >/dev/null || { echo 'Stage-J promotion fingerprint mismatch' >&2; exit 3; }
MANIFEST_SHA="$(sha256sum "$MANIFEST" | awk '{print $1}')"

label="stagej_nextmate_selfw${B300_STAGEI_PREPARED_SELF_WIDTH}_selfd${B300_STAGEI_PREPARED_SELF_DISTANCE}_matew${B300_STAGEI_PREPARED_MATE_WIDTH}_mated${B300_STAGEI_PREPARED_MATE_DISTANCE}"
control_label="stagej_nextself_selfw${B300_STAGEI_PREPARED_SELF_WIDTH}_selfd${B300_STAGEI_PREPARED_SELF_DISTANCE}"
cat >"$PROMOTION_ENV" <<EOF
B300_STAGEJ_PROMOTION_VALIDATED=1
B300_STAGEJ_PROMOTION_BIN=$(printf '%q' "$B300_STAGEI_PREPARED_BIN")
B300_STAGEJ_PROMOTION_BIN_SHA256=$FINAL_SHA
B300_STAGEJ_PROMOTION_THREADS=$B300_STAGEI_PREPARED_THREADS
B300_STAGEJ_PROMOTION_CONTROL_BIN=$(printf '%q' "$B300_STAGEI_PREPARED_CONTROL_BIN")
B300_STAGEJ_PROMOTION_CONTROL_SHA256=$CONTROL_SHA
B300_STAGEJ_PROMOTION_CONTROL_THREADS=$B300_STAGEI_PREPARED_CONTROL_THREADS
B300_STAGEJ_PROMOTION_SELF_WIDTH=$B300_STAGEI_PREPARED_SELF_WIDTH
B300_STAGEJ_PROMOTION_SELF_DISTANCE=$B300_STAGEI_PREPARED_SELF_DISTANCE
B300_STAGEJ_PROMOTION_SELF_EVICT=$(printf '%q' "$SELF_EVICT")
B300_STAGEJ_PROMOTION_MATE_WIDTH=$B300_STAGEI_PREPARED_MATE_WIDTH
B300_STAGEJ_PROMOTION_MATE_DISTANCE=$B300_STAGEI_PREPARED_MATE_DISTANCE
B300_STAGEJ_PROMOTION_MATE_EVICT=$(printf '%q' "$MATE_EVICT")
B300_STAGEJ_PROMOTION_SPEEDUP=$B300_STAGEI_PREPARED_STAGED_SPEEDUP
B300_STAGEJ_PROMOTION_INPUT_STAGE_F_ENV=$(printf '%q' "$INPUT_ENV")
B300_STAGEJ_PROMOTION_INPUT_STAGE_F_ENV_SHA256=$INPUT_SHA
B300_STAGEJ_PROMOTION_WINNER_ENV=$(printf '%q' "$WINNER_ENV")
B300_STAGEJ_PROMOTION_WINNER_ENV_SHA256=$WINNER_SHA
B300_STAGEJ_PROMOTION_MANIFEST=$(printf '%q' "$MANIFEST")
B300_STAGEJ_PROMOTION_MANIFEST_SHA256=$MANIFEST_SHA
B300_STAGEJ_PROMOTION_BUILD_DIR=$(printf '%q' "$STAGEJ_BUILD_DIR")
EOF

{
  printf 'B300_STAGEJ_PREPARED=1\n'
  printf 'B300_STAGEJ_PREPARED_BIN=%q\n' "$B300_STAGEI_PREPARED_BIN"
  printf 'B300_STAGEJ_PREPARED_LABEL=%q\n' "$label"
  printf 'B300_STAGEJ_PREPARED_THREADS=%q\n' "$B300_STAGEI_PREPARED_THREADS"
  printf 'B300_STAGEJ_PREPARED_CONTROL_BIN=%q\n' "$B300_STAGEI_PREPARED_CONTROL_BIN"
  printf 'B300_STAGEJ_PREPARED_CONTROL_LABEL=%q\n' "$control_label"
  printf 'B300_STAGEJ_PREPARED_CONTROL_THREADS=%q\n' "$B300_STAGEI_PREPARED_CONTROL_THREADS"
  printf 'B300_STAGEJ_PREPARED_SELF_WIDTH=%q\n' "$B300_STAGEI_PREPARED_SELF_WIDTH"
  printf 'B300_STAGEJ_PREPARED_SELF_DISTANCE=%q\n' "$B300_STAGEI_PREPARED_SELF_DISTANCE"
  printf 'B300_STAGEJ_PREPARED_SELF_EVICT=%q\n' "$SELF_EVICT"
  printf 'B300_STAGEJ_PREPARED_MATE_WIDTH=%q\n' "$B300_STAGEI_PREPARED_MATE_WIDTH"
  printf 'B300_STAGEJ_PREPARED_MATE_DISTANCE=%q\n' "$B300_STAGEI_PREPARED_MATE_DISTANCE"
  printf 'B300_STAGEJ_PREPARED_MATE_EVICT=%q\n' "$MATE_EVICT"
  printf 'B300_STAGEJ_PREPARED_STAGED_SPEEDUP=%q\n' "$B300_STAGEI_PREPARED_STAGED_SPEEDUP"
  printf 'B300_STAGEJ_PREPARED_MANIFEST=%q\n' "$MANIFEST"
  printf 'B300_STAGEJ_PREPARED_PROMOTION_ENV=%q\n' "$PROMOTION_ENV"
  printf 'B300_STAGEJ_PREPARED_BUILD_DIR=%q\n' "$STAGEJ_BUILD_DIR"
} >"$PREPARE_ENV"

if [[ "$PREPARE_ONLY" == 1 ]]; then
  cat "$PREPARE_ENV"
  echo "STAGE J PREPARED env=$PREPARE_ENV label=$label speedup=${B300_STAGEI_PREPARED_STAGED_SPEEDUP}x namespace_isolated=1 build_dir=$STAGEJ_BUILD_DIR" >&2
  exit 0
fi

echo "=== Stage J full-prime race: $label vs $control_label vs profiled warp/orbit ===" >&2
exec env \
  PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" MAX_WINDOW="$MAX_WINDOW" FORCED_TARGET_MIB="$TARGET_MIB" \
  FORCED_OVERRIDE_BIN="$B300_STAGEI_PREPARED_BIN" FORCED_OVERRIDE_LABEL="$label" FORCED_OVERRIDE_THREADS="$B300_STAGEI_PREPARED_THREADS" \
  FORCED_BASE_BIN="$B300_STAGEI_PREPARED_CONTROL_BIN" FORCED_BASE_LABEL="$control_label" FORCED_BASE_THREADS="$B300_STAGEI_PREPARED_CONTROL_THREADS" \
  REBUILD_BUCKETS="$REBUILD_BUCKETS" SELECT_ONLY="$SELECT_ONLY" PREFIX="$RACE_PREFIX" \
  "$ONEESAN_ROOT/scripts/run/b300x8-race-external-forced-profiled-once.sh" 27 "$@"
