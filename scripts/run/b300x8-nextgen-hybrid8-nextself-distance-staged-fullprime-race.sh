#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"

N="${1:-27}"; if (($#>0)); then shift; fi
[[ "$N" == 27 ]] || { echo 'Stage-G full-prime race targets n=27' >&2; exit 2; }
PROFILE_FILE="${PROFILE_FILE:-$ONEESAN_ROOT/work/b300_hbm_profile_refined21.env}"; [[ -f "$PROFILE_FILE" ]] || exit 2
ARCH="${ARCH:-native}"; TARGET_MIB="${TARGET_MIB:-65536}"; MAX_WINDOW="${MAX_WINDOW:-14}"
RUN_STAGED="${RUN_STAGED:-1}"; RUN_STAGE_F="${RUN_STAGE_F:-1}"; PREPARE_ONLY="${PREPARE_ONLY:-0}"; SELECT_ONLY="${SELECT_ONLY:-1}"; REBUILD_BUCKETS="${REBUILD_BUCKETS:-1}"
MIN_SPEEDUP="${MIN_SPEEDUP:-1.002}"; DISTANCE_LIST="${DISTANCE_LIST:-1 2 4}"
STAGED_PREFIX="${STAGED_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextself_distance_staged}"
STAGE_F_PREFIX="${STAGE_F_PREFIX:-${STAGED_PREFIX}.stagef}"; STAGE_F_ENV="${STAGE_F_ENV:-${STAGE_F_PREFIX}_winner.env}"
WINNER_ENV="${WINNER_ENV:-${STAGED_PREFIX}_winner.env}"; MANIFEST="${MANIFEST:-${WINNER_ENV%.env}_promotion-inputs.sha256}"
RACE_PREFIX="${RACE_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextself_distance_fullprime_n27}"; PREPARE_ENV="${PREPARE_ENV:-${RACE_PREFIX}_prepared.env}"
for x in RUN_STAGED RUN_STAGE_F PREPARE_ONLY SELECT_ONLY REBUILD_BUCKETS; do v="${!x}"; [[ "$v" == 0 || "$v" == 1 ]] || exit 2; done
command -v sha256sum >/dev/null || exit 2

if [[ "$RUN_STAGED" == 1 ]]; then
  ARCH="$ARCH" MOD="${MOD:-4294967291}" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" MIN_SPEEDUP="$MIN_SPEEDUP" DISTANCE_LIST="$DISTANCE_LIST" \
    RUN_STAGE_F="$RUN_STAGE_F" PREFIX="$STAGED_PREFIX" STAGE_F_PREFIX="$STAGE_F_PREFIX" STAGE_F_ENV="$STAGE_F_ENV" FINAL_ENV="$WINNER_ENV" \
    bash "$ONEESAN_ROOT/scripts/bench/b300-nextgen-hybrid8-nextself-distance-staged-calibrate.sh"
fi
[[ -s "$WINNER_ENV" ]] || { echo "missing Stage-G env=$WINNER_ENV" >&2; exit 3; }
# shellcheck disable=SC1090
source "$WINNER_ENV"
for k in B300_HYBRID8_NEXTSELF_DISTANCE_STAGED_VALIDATED B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_DISTANCE B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH \
  B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_THREADS B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPEEDUP_VS_D1 B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPILL_FREE \
  B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_THREADS B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_STAGE_ROWS B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_STAGE_RESIDUE \
  B300_HYBRID8_NEXTSELF_DISTANCE_THRESHOLD B300_HYBRID8_NEXTSELF_DISTANCE_STAGE_F_ENV; do [[ -n "${!k+x}" ]] || { echo "Stage-G env missing $k" >&2; exit 3; }; done
[[ "$B300_HYBRID8_NEXTSELF_DISTANCE_STAGED_VALIDATED" == 1 && "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPILL_FREE" == 1 ]] || { echo 'Stage G not promotable' >&2; exit 4; }
case "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH" in 1|2|4|8);;*) exit 3;; esac
case "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_DISTANCE" in 2|4);;*) echo 'Stage G winner must improve beyond distance=1' >&2; exit 4;; esac
for k in B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_THREADS B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_THREADS; do v="${!k}"; [[ "$v" =~ ^[0-9]+$ ]] && ((v>=32&&v<=1024&&v%32==0)) || exit 3; done
[[ -x "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN" && -x "$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN" && -s "$B300_HYBRID8_NEXTSELF_DISTANCE_STAGE_F_ENV" ]] || exit 3
python3 - "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPEEDUP_VS_D1" "$MIN_SPEEDUP" <<'PY'
import sys
if float(sys.argv[1]) < float(sys.argv[2]): raise SystemExit('Stage-G speedup gate failed')
PY

if [[ "$RUN_STAGED" == 1 ]]; then
  tmp="${MANIFEST}.tmp"; mkdir -p "$(dirname "$MANIFEST")"
  sha256sum "$WINNER_ENV" "$B300_HYBRID8_NEXTSELF_DISTANCE_STAGE_F_ENV" "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN" "$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN" >"$tmp"; mv "$tmp" "$MANIFEST"
else
  [[ -s "$MANIFEST" ]] || { echo 'missing Stage-G manifest' >&2; exit 3; }
fi
sha256sum -c "$MANIFEST" >/dev/null || { echo 'Stage-G fingerprint mismatch' >&2; exit 3; }
FINAL_SHA="$(sha256sum "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN" | awk '{print $1}')"; REF_SHA="$(sha256sum "$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN" | awk '{print $1}')"; MANIFEST_SHA="$(sha256sum "$MANIFEST" | awk '{print $1}')"
PROMOTION_ENV="${RACE_PREFIX}_promotion.env"
cat >"$PROMOTION_ENV" <<EOF
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_VALIDATED=1
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_WIDTH=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_DISTANCE=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_DISTANCE
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_BIN=$(printf '%q' "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN")
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_BIN_SHA256=$FINAL_SHA
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_REFERENCE_BIN=$(printf '%q' "$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN")
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_REFERENCE_SHA256=$REF_SHA
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_MANIFEST=$(printf '%q' "$MANIFEST")
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_MANIFEST_SHA256=$MANIFEST_SHA
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_STAGE_ROWS=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_STAGE_ROWS
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_STAGE_RESIDUE=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_STAGE_RESIDUE
B300_HYBRID8_NEXTSELF_DISTANCE_PROMOTION_SPEEDUP_VS_D1=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPEEDUP_VS_D1
EOF
label="nextgen_hybrid8_nextself_w${B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH}_d${B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_DISTANCE}_t${B300_HYBRID8_NEXTSELF_DISTANCE_THRESHOLD}"
ref_label="nextgen_hybrid8_nextself_w${B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH}_d1_t${B300_HYBRID8_NEXTSELF_DISTANCE_THRESHOLD}"
if [[ "$PREPARE_ONLY" == 1 ]]; then
  {
    printf 'B300_STAGEG_PREPARED=1\n'
    printf 'B300_STAGEG_PREPARED_WIDTH=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH"
    printf 'B300_STAGEG_PREPARED_DISTANCE=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_DISTANCE"
    printf 'B300_STAGEG_PREPARED_BIN=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN"
    printf 'B300_STAGEG_PREPARED_LABEL=%q\n' "$label"
    printf 'B300_STAGEG_PREPARED_THREADS=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_THREADS"
    printf 'B300_STAGEG_PREPARED_REFERENCE_BIN=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN"
    printf 'B300_STAGEG_PREPARED_REFERENCE_LABEL=%q\n' "$ref_label"
    printf 'B300_STAGEG_PREPARED_REFERENCE_THREADS=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_THREADS"
    printf 'B300_STAGEG_PREPARED_SPEEDUP_VS_D1=%q\n' "$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPEEDUP_VS_D1"
    printf 'B300_STAGEG_PREPARED_MANIFEST=%q\n' "$MANIFEST"
    printf 'B300_STAGEG_PREPARED_PROMOTION_ENV=%q\n' "$PROMOTION_ENV"
  } >"$PREPARE_ENV"
  cat "$PREPARE_ENV"
  echo "STAGE G PREPARED width=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_WIDTH distance=$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_DISTANCE speedup=${B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_SPEEDUP_VS_D1}x" >&2
  exit 0
fi
exec env PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" MAX_WINDOW="$MAX_WINDOW" FORCED_TARGET_MIB="$TARGET_MIB" \
  FORCED_OVERRIDE_BIN="$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_BIN" FORCED_OVERRIDE_LABEL="$label" FORCED_OVERRIDE_THREADS="$B300_HYBRID8_NEXTSELF_DISTANCE_FINAL_THREADS" \
  FORCED_BASE_BIN="$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_BIN" FORCED_BASE_LABEL="$ref_label" FORCED_BASE_THREADS="$B300_HYBRID8_NEXTSELF_DISTANCE_REFERENCE_THREADS" \
  REBUILD_BUCKETS="$REBUILD_BUCKETS" SELECT_ONLY="$SELECT_ONLY" PREFIX="$RACE_PREFIX" "$ONEESAN_ROOT/scripts/run/b300x8-race-external-forced-profiled-once.sh" 27 "$@"
