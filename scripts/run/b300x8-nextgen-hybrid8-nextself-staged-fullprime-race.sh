#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"

N="${1:-27}"
if (($#>0)); then shift; fi
[[ "$N" == 27 ]] || { echo 'hybrid8 next-self staged full-prime race targets n=27' >&2; exit 2; }

PROFILE_FILE="${PROFILE_FILE:-$ONEESAN_ROOT/work/b300_hbm_profile_refined21.env}"
[[ -f "$PROFILE_FILE" ]] || { echo "missing PROFILE_FILE=$PROFILE_FILE" >&2; exit 2; }
ARCH="${ARCH:-native}"
TARGET_MIB="${TARGET_MIB:-65536}"
MAX_WINDOW="${MAX_WINDOW:-14}"
RUN_STAGED="${RUN_STAGED:-1}"
RUN_HYBRID_STAGE="${RUN_HYBRID_STAGE:-1}"
PREPARE_ONLY="${PREPARE_ONLY:-0}"
SELECT_ONLY="${SELECT_ONLY:-1}"
REBUILD_BUCKETS="${REBUILD_BUCKETS:-1}"
MIN_SPEEDUP="${MIN_SPEEDUP:-1.01}"
STAGED_PREFIX="${STAGED_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextself_staged}"
HYBRID_PREFIX="${HYBRID_PREFIX:-${STAGED_PREFIX}.hybrid8}"
HYBRID_WINNER_ENV="${HYBRID_WINNER_ENV:-${HYBRID_PREFIX}_winner.env}"
WINNER_ENV="${WINNER_ENV:-${STAGED_PREFIX}_winner.env}"
MANIFEST="${MANIFEST:-${WINNER_ENV%.env}_promotion-inputs.sha256}"
RACE_PREFIX="${RACE_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextself_staged_fullprime_n27}"
PREPARE_ENV="${PREPARE_ENV:-${RACE_PREFIX}_prepared.env}"
for x in RUN_STAGED RUN_HYBRID_STAGE PREPARE_ONLY SELECT_ONLY REBUILD_BUCKETS; do
  v="${!x}"; [[ "$v" == 0 || "$v" == 1 ]] || { echo "$x must be 0/1" >&2; exit 2; }
done
command -v sha256sum >/dev/null || { echo 'sha256sum required' >&2; exit 2; }

if [[ "$RUN_STAGED" == 1 ]]; then
  echo '=== hybrid8 next-self staged calibration ===' >&2
  ARCH="$ARCH" MOD="${MOD:-4294967291}" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" MIN_SPEEDUP="$MIN_SPEEDUP" \
    RUN_HYBRID_STAGE="$RUN_HYBRID_STAGE" PREFIX="$STAGED_PREFIX" HYBRID_PREFIX="$HYBRID_PREFIX" \
    HYBRID_WINNER_ENV="$HYBRID_WINNER_ENV" FINAL_ENV="$WINNER_ENV" \
    bash "$ONEESAN_ROOT/scripts/bench/b300-nextgen-hybrid8-nextself-staged-calibrate.sh"
fi

[[ -s "$WINNER_ENV" ]] || { echo "missing Stage-F WINNER_ENV=$WINNER_ENV" >&2; exit 3; }
# shellcheck disable=SC1090
source "$WINNER_ENV"
for key in \
  B300_HYBRID8_NEXTSELF_STAGED_VALIDATED B300_HYBRID8_NEXTSELF_FINAL_ENABLED \
  B300_HYBRID8_NEXTSELF_FINAL_BIN B300_HYBRID8_NEXTSELF_FINAL_THREADS B300_HYBRID8_NEXTSELF_FINAL_WALL_S \
  B300_HYBRID8_NEXTSELF_FINAL_SPEEDUP_VS_HYBRID8 B300_HYBRID8_NEXTSELF_FINAL_SPILL_FREE \
  B300_HYBRID8_NEXTSELF_CONTROL_BIN B300_HYBRID8_NEXTSELF_CONTROL_THREADS B300_HYBRID8_NEXTSELF_CONTROL_SPILL_FREE \
  B300_HYBRID8_NEXTSELF_FINAL_STAGE_ROWS B300_HYBRID8_NEXTSELF_FINAL_STAGE_RESIDUE B300_HYBRID8_NEXTSELF_THRESHOLD \
  B300_HYBRID8_NEXTSELF_STAGE_E_ENV; do
  [[ -n "${!key+x}" ]] || { echo "Stage-F env missing $key" >&2; exit 3; }
done
[[ "$B300_HYBRID8_NEXTSELF_STAGED_VALIDATED" == 1 && "$B300_HYBRID8_NEXTSELF_FINAL_ENABLED" == 1 ]] || {
  echo 'hybrid8 next-self did not survive staged validation; refusing full-prime promotion' >&2
  exit 4
}
[[ "$B300_HYBRID8_NEXTSELF_FINAL_SPILL_FREE" == 1 && "$B300_HYBRID8_NEXTSELF_CONTROL_SPILL_FREE" == 1 ]] || {
  echo 'hybrid8 next-self promotion lacks explicit spill-free proof' >&2
  exit 4
}
[[ "$B300_HYBRID8_NEXTSELF_THRESHOLD" =~ ^[0-9]+$ ]] || exit 3
[[ "$B300_HYBRID8_NEXTSELF_FINAL_STAGE_ROWS" =~ ^[1-9][0-9]*$ ]] && ((B300_HYBRID8_NEXTSELF_FINAL_STAGE_ROWS<=28)) || exit 3
[[ -n "$B300_HYBRID8_NEXTSELF_FINAL_STAGE_RESIDUE" ]] || exit 3
for key in B300_HYBRID8_NEXTSELF_FINAL_THREADS B300_HYBRID8_NEXTSELF_CONTROL_THREADS; do
  v="${!key}"; [[ "$v" =~ ^[0-9]+$ ]] && ((v>=32 && v<=1024 && v%32==0)) || { echo "bad $key=$v" >&2; exit 3; }
done
[[ -x "$B300_HYBRID8_NEXTSELF_FINAL_BIN" && -x "$B300_HYBRID8_NEXTSELF_CONTROL_BIN" ]] || { echo 'Stage-F final/control binary missing' >&2; exit 3; }
[[ -s "$B300_HYBRID8_NEXTSELF_STAGE_E_ENV" ]] || { echo 'Stage-E provenance env missing' >&2; exit 3; }
python3 - "$B300_HYBRID8_NEXTSELF_FINAL_SPEEDUP_VS_HYBRID8" "$MIN_SPEEDUP" <<'PY'
import sys
speed,need=map(float,sys.argv[1:])
if speed<need: raise SystemExit(f'Stage-F speedup {speed:.9f}x below {need:.9f}x')
PY

if [[ "$RUN_STAGED" == 1 ]]; then
  tmp="${MANIFEST}.tmp"
  mkdir -p "$(dirname "$MANIFEST")"
  sha256sum "$WINNER_ENV" "$B300_HYBRID8_NEXTSELF_STAGE_E_ENV" "$B300_HYBRID8_NEXTSELF_FINAL_BIN" "$B300_HYBRID8_NEXTSELF_CONTROL_BIN" >"$tmp"
  mv "$tmp" "$MANIFEST"
else
  [[ -s "$MANIFEST" ]] || { echo "missing Stage-F promotion manifest=$MANIFEST; rerun with RUN_STAGED=1" >&2; exit 3; }
fi
sha256sum -c "$MANIFEST" >/dev/null || { echo 'Stage-F promotion fingerprint mismatch; rerun staged calibration' >&2; exit 3; }

FINAL_SHA="$(sha256sum "$B300_HYBRID8_NEXTSELF_FINAL_BIN" | awk '{print $1}')"
CONTROL_SHA="$(sha256sum "$B300_HYBRID8_NEXTSELF_CONTROL_BIN" | awk '{print $1}')"
ENV_SHA="$(sha256sum "$WINNER_ENV" | awk '{print $1}')"
STAGE_E_SHA="$(sha256sum "$B300_HYBRID8_NEXTSELF_STAGE_E_ENV" | awk '{print $1}')"
MANIFEST_SHA="$(sha256sum "$MANIFEST" | awk '{print $1}')"
PROMOTION_ENV="${RACE_PREFIX}_promotion.env"
cat >"$PROMOTION_ENV" <<EOF
B300_HYBRID8_NEXTSELF_PROMOTION_VALIDATED=1
B300_HYBRID8_NEXTSELF_PROMOTION_SPILL_FREE=1
B300_HYBRID8_NEXTSELF_PROMOTION_THRESHOLD=$B300_HYBRID8_NEXTSELF_THRESHOLD
B300_HYBRID8_NEXTSELF_PROMOTION_BIN=$(printf '%q' "$B300_HYBRID8_NEXTSELF_FINAL_BIN")
B300_HYBRID8_NEXTSELF_PROMOTION_THREADS=$B300_HYBRID8_NEXTSELF_FINAL_THREADS
B300_HYBRID8_NEXTSELF_PROMOTION_SHA256=$FINAL_SHA
B300_HYBRID8_NEXTSELF_PROMOTION_CONTROL_BIN=$(printf '%q' "$B300_HYBRID8_NEXTSELF_CONTROL_BIN")
B300_HYBRID8_NEXTSELF_PROMOTION_CONTROL_THREADS=$B300_HYBRID8_NEXTSELF_CONTROL_THREADS
B300_HYBRID8_NEXTSELF_PROMOTION_CONTROL_SHA256=$CONTROL_SHA
B300_HYBRID8_NEXTSELF_PROMOTION_WINNER_ENV_SHA256=$ENV_SHA
B300_HYBRID8_NEXTSELF_PROMOTION_STAGE_E_ENV_SHA256=$STAGE_E_SHA
B300_HYBRID8_NEXTSELF_PROMOTION_MANIFEST=$(printf '%q' "$MANIFEST")
B300_HYBRID8_NEXTSELF_PROMOTION_MANIFEST_SHA256=$MANIFEST_SHA
B300_HYBRID8_NEXTSELF_PROMOTION_FINAL_STAGE_ROWS=$B300_HYBRID8_NEXTSELF_FINAL_STAGE_ROWS
B300_HYBRID8_NEXTSELF_PROMOTION_FINAL_STAGE_RESIDUE=$B300_HYBRID8_NEXTSELF_FINAL_STAGE_RESIDUE
B300_HYBRID8_NEXTSELF_PROMOTION_STAGED_SPEEDUP=$B300_HYBRID8_NEXTSELF_FINAL_SPEEDUP_VS_HYBRID8
EOF

label="nextgen_hybrid8_nextself_t${B300_HYBRID8_NEXTSELF_THRESHOLD}"
control_label="nextgen_hybrid8_t${B300_HYBRID8_NEXTSELF_THRESHOLD}"
if [[ "$PREPARE_ONLY" == 1 ]]; then
  mkdir -p "$(dirname "$PREPARE_ENV")"
  {
    printf 'B300_HYBRID8_NEXTSELF_PREPARED=1\n'
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_BIN=%q\n' "$B300_HYBRID8_NEXTSELF_FINAL_BIN"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_LABEL=%q\n' "$label"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_THREADS=%q\n' "$B300_HYBRID8_NEXTSELF_FINAL_THREADS"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_BIN=%q\n' "$B300_HYBRID8_NEXTSELF_CONTROL_BIN"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_LABEL=%q\n' "$control_label"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_THREADS=%q\n' "$B300_HYBRID8_NEXTSELF_CONTROL_THREADS"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_STAGED_SPEEDUP=%q\n' "$B300_HYBRID8_NEXTSELF_FINAL_SPEEDUP_VS_HYBRID8"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_FINAL_STAGE_ROWS=%q\n' "$B300_HYBRID8_NEXTSELF_FINAL_STAGE_ROWS"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_FINAL_STAGE_RESIDUE=%q\n' "$B300_HYBRID8_NEXTSELF_FINAL_STAGE_RESIDUE"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_MANIFEST=%q\n' "$MANIFEST"
    printf 'B300_HYBRID8_NEXTSELF_PREPARED_PROMOTION_ENV=%q\n' "$PROMOTION_ENV"
  } >"$PREPARE_ENV"
  cat "$PREPARE_ENV"
  echo "HYBRID8 NEXTSELF PREPARED env=$PREPARE_ENV label=$label control=$control_label speedup=${B300_HYBRID8_NEXTSELF_FINAL_SPEEDUP_VS_HYBRID8}x" >&2
  exit 0
fi

echo "=== full-prime race: $label vs $control_label vs profiled warp/orbit ===" >&2
exec env \
  PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" MAX_WINDOW="$MAX_WINDOW" FORCED_TARGET_MIB="$TARGET_MIB" \
  FORCED_OVERRIDE_BIN="$B300_HYBRID8_NEXTSELF_FINAL_BIN" FORCED_OVERRIDE_LABEL="$label" FORCED_OVERRIDE_THREADS="$B300_HYBRID8_NEXTSELF_FINAL_THREADS" \
  FORCED_BASE_BIN="$B300_HYBRID8_NEXTSELF_CONTROL_BIN" FORCED_BASE_LABEL="$control_label" FORCED_BASE_THREADS="$B300_HYBRID8_NEXTSELF_CONTROL_THREADS" \
  REBUILD_BUCKETS="$REBUILD_BUCKETS" SELECT_ONLY="$SELECT_ONLY" PREFIX="$RACE_PREFIX" \
  "$ONEESAN_ROOT/scripts/run/b300x8-race-external-forced-profiled-once.sh" 27 "$@"
