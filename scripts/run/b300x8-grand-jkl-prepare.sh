#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"

N="${1:-27}"; if (($#>0)); then shift; fi
[[ "$N" == 27 ]] || { echo 'grand J/K/L prepare targets n=27' >&2; exit 2; }
PROFILE_FILE="${PROFILE_FILE:-$ONEESAN_ROOT/work/b300_hbm_profile_refined21.env}"; [[ -s "$PROFILE_FILE" ]] || exit 2
ARCH="${ARCH:-native}"; MAX_WINDOW="${MAX_WINDOW:-14}"; SMOKE_PRIME="${SMOKE_PRIME:-4294967291}"
FORCED_TARGET_MIB="${FORCED_TARGET_MIB:-65536}"; BUCKET_TARGET_MIB="${BUCKET_TARGET_MIB:-16384}"; REBUILD_BUCKETS="${REBUILD_BUCKETS:-1}"; WORK_ROOT="${WORK_ROOT:-$ONEESAN_ROOT/work}"
STAGEJ_MIN_SPEEDUP="${STAGEJ_MIN_SPEEDUP:-1.002}"; STAGEK_MIN_SPEEDUP="${STAGEK_MIN_SPEEDUP:-1.002}"
MATE_WIDTH_LIST="${MATE_WIDTH_LIST:-1 2 4 8}"; MATE_DISTANCE_LIST="${MATE_DISTANCE_LIST:-1 2 4}"; MATE_EVICT_BASE="${MATE_EVICT_BASE:-default}"; MATE_EVICT_LIST="${MATE_EVICT_LIST:-default normal last}"
PREFIX="${PREFIX:-$ONEESAN_ROOT/work/b300_grand_jkl_prepare_n27}"
BASE_PREFIX="${BASE_PREFIX:-${PREFIX}.base}"; BASE_SELECTED_ENV="${BASE_SELECTED_ENV:-${BASE_PREFIX}.selected.env}"; STAGE_F_ENV="${STAGE_F_ENV:-${BASE_PREFIX}.hybrid8-nextself_winner.env}"; BASE_STAGEI_PREPARE_ENV="${BASE_STAGEI_PREPARE_ENV:-${BASE_PREFIX}.stagei-evict.prepared.env}"
STAGEJ_PREFIX="${STAGEJ_PREFIX:-${PREFIX}.stagej}"; STAGEJ_WINNER_ENV="${STAGEJ_WINNER_ENV:-${STAGEJ_PREFIX}_winner.env}"; STAGEJ_PREPARE_ENV="${STAGEJ_PREPARE_ENV:-${PREFIX}.stagej.prepared.env}"; STAGEJ_RACE_PREFIX="${STAGEJ_RACE_PREFIX:-${PREFIX}.stagej.promote}"
STAGEK_PREFIX="${STAGEK_PREFIX:-${PREFIX}.stagek}"; STAGEK_WINNER_ENV="${STAGEK_WINNER_ENV:-${STAGEK_PREFIX}_winner.env}"; STAGEK_PREPARE_ENV="${STAGEK_PREPARE_ENV:-${PREFIX}.stagek.prepared.env}"; STAGEK_RACE_PREFIX="${STAGEK_RACE_PREFIX:-${PREFIX}.stagek.promote}"
OUT_ENV="${OUT_ENV:-${PREFIX}.prepared.env}"
mkdir -p "$(dirname "$OUT_ENV")" "$WORK_ROOT"
case "$MATE_EVICT_BASE" in default|normal|last) ;; *) exit 2;; esac
for x in MAX_WINDOW FORCED_TARGET_MIB BUCKET_TARGET_MIB SMOKE_PRIME; do v="${!x}"; [[ "$v" =~ ^[1-9][0-9]*$ ]] || exit 2; done
python3 - "$STAGEJ_MIN_SPEEDUP" "$STAGEK_MIN_SPEEDUP" <<'PY'
import sys
for n,v in zip(('STAGEJ_MIN_SPEEDUP','STAGEK_MIN_SPEEDUP'),map(float,sys.argv[1:])):
    if v < 1.0: raise SystemExit(f'{n} must be >=1')
PY

# The incumbent grand selector is intentionally the only complete-prime work
# before the final J/K/L refinement race. J and K below are PREPARE_ONLY.
echo '=== J/K/L prepare: incumbent grand ===' >&2
PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" MAX_WINDOW="$MAX_WINDOW" SMOKE_PRIME="$SMOKE_PRIME" FORCED_TARGET_MIB="$FORCED_TARGET_MIB" BUCKET_TARGET_MIB="$BUCKET_TARGET_MIB" REBUILD_BUCKETS="$REBUILD_BUCKETS" WORK_ROOT="$WORK_ROOT" PREFIX="$BASE_PREFIX" \
  bash "$ONEESAN_ROOT/scripts/run/b300x8-grand-firstpass.sh" 27 "$@"
[[ -s "$BASE_SELECTED_ENV" ]] || { echo 'J/K/L base selected env missing' >&2; exit 3; }
# shellcheck disable=SC1090
source "$BASE_SELECTED_ENV"
[[ "${B300_GRAND_SELECTED_VALIDATED:-0}" == 1 ]] || exit 3
BASE_BIN="$B300_GRAND_SELECTED_BINARY"; BASE_BACKEND="$B300_GRAND_SELECTED_BACKEND"; BASE_PROFILE="$B300_GRAND_SELECTED_PROFILE"; BASE_RUNTIME="$B300_GRAND_SELECTED_RUNTIME_KIND"; BASE_THREADS="$B300_GRAND_SELECTED_THREADS"
BASE_HEAD="$B300_GRAND_SELECTED_HEAD_SHA"; BASE_DIRTY="$B300_GRAND_SELECTED_HEAD_DIRTY"; BASE_PROFILE_FILE="$B300_GRAND_SELECTED_PROFILE_FILE"; BASE_PROFILE_SHA="$B300_GRAND_SELECTED_PROFILE_SHA256"; BASE_PRIME="$B300_GRAND_SELECTED_SMOKE_PRIME"; BASE_MAXW="$B300_GRAND_SELECTED_MAX_WINDOW"
[[ -x "$BASE_BIN" && "$BASE_PRIME" == "$SMOKE_PRIME" ]] || exit 3
if [[ ! -s "$STAGE_F_ENV" ]]; then
  {
    printf 'B300_JKL_PREPARED=1\n'; printf 'B300_JKL_REFINEMENT_APPLICABLE=0\n'; printf 'B300_JKL_REASON=no_stage_f_env\n'; printf 'B300_JKL_BASE_SELECTED_ENV=%q\n' "$BASE_SELECTED_ENV";
  } >"$OUT_ENV"
  cat "$OUT_ENV"; exit 0
fi

SELF_EVICT=default
if [[ -s "$BASE_STAGEI_PREPARE_ENV" ]]; then
  # shellcheck disable=SC1090
  source "$BASE_STAGEI_PREPARE_ENV"
  if [[ "${B300_EVICT_PREPARED:-0}" == 1 ]]; then SELF_EVICT="$B300_EVICT_HINT"
  elif [[ "${B300_STAGEI_PREPARED:-0}" == 1 ]]; then SELF_EVICT="$B300_STAGEI_PREPARED_HINT"
  fi
fi
case "$SELF_EVICT" in default|normal|last) ;; *) echo "bad inherited self evict=$SELF_EVICT" >&2; exit 3;; esac

# Stage J: independent mate geometry, staged only.
echo "=== J/K/L prepare: Stage J self_evict=$SELF_EVICT ===" >&2
set +e
PROFILE_FILE="$BASE_PROFILE_FILE" ARCH="$ARCH" TARGET_MIB="$FORCED_TARGET_MIB" MAX_WINDOW="$BASE_MAXW" MOD="$BASE_PRIME" INPUT_ENV="$STAGE_F_ENV" \
  RUN_STAGED=1 PREPARE_ONLY=1 MIN_SPEEDUP="$STAGEJ_MIN_SPEEDUP" MATE_WIDTH_LIST="$MATE_WIDTH_LIST" MATE_DISTANCE_LIST="$MATE_DISTANCE_LIST" SELF_EVICT="$SELF_EVICT" MATE_EVICT="$MATE_EVICT_BASE" \
  STAGED_PREFIX="$STAGEJ_PREFIX" WINNER_ENV="$STAGEJ_WINNER_ENV" RACE_PREFIX="$STAGEJ_RACE_PREFIX" PREPARE_ENV="$STAGEJ_PREPARE_ENV" \
  bash "$ONEESAN_ROOT/scripts/run/b300x8-nextgen-hybrid8-nextmate-geometry-stagej-staged-fullprime-race.sh" 27
J_RC=$?
set -e
if ((J_RC==4)); then
  {
    printf 'B300_JKL_PREPARED=1\n'; printf 'B300_JKL_REFINEMENT_APPLICABLE=0\n'; printf 'B300_JKL_REASON=stagej_rejected\n'; printf 'B300_JKL_BASE_SELECTED_ENV=%q\n' "$BASE_SELECTED_ENV";
  } >"$OUT_ENV"
  cat "$OUT_ENV"; exit 0
fi
((J_RC==0)) || exit "$J_RC"
[[ -s "$STAGEJ_PREPARE_ENV" && -s "$STAGEJ_WINNER_ENV" ]] || exit 3
# shellcheck disable=SC1090
source "$STAGEJ_PREPARE_ENV"
for k in B300_STAGEJ_PREPARED B300_STAGEJ_PREPARED_MOD B300_STAGEJ_PREPARED_BIN B300_STAGEJ_PREPARED_LABEL B300_STAGEJ_PREPARED_THREADS B300_STAGEJ_PREPARED_CONTROL_BIN B300_STAGEJ_PREPARED_CONTROL_LABEL B300_STAGEJ_PREPARED_CONTROL_THREADS B300_STAGEJ_PREPARED_MANIFEST; do [[ -n "${!k+x}" ]] || { echo "Stage-J prepare missing $k" >&2; exit 3; }; done
[[ "$B300_STAGEJ_PREPARED" == 1 && "$B300_STAGEJ_PREPARED_MOD" == "$BASE_PRIME" && -x "$B300_STAGEJ_PREPARED_BIN" && -x "$B300_STAGEJ_PREPARED_CONTROL_BIN" ]] || exit 3
sha256sum -c "$B300_STAGEJ_PREPARED_MANIFEST" >/dev/null || { echo 'Stage-J manifest failed in J/K/L prepare' >&2; exit 3; }
J_BIN="$B300_STAGEJ_PREPARED_BIN"; J_LABEL="$B300_STAGEJ_PREPARED_LABEL"; J_THREADS="$B300_STAGEJ_PREPARED_THREADS"; J_CONTROL_BIN="$B300_STAGEJ_PREPARED_CONTROL_BIN"; J_CONTROL_LABEL="$B300_STAGEJ_PREPARED_CONTROL_LABEL"; J_CONTROL_THREADS="$B300_STAGEJ_PREPARED_CONTROL_THREADS"

# Stage K: mate eviction only. A rejection keeps Stage J as the upstream.
K_OK=0
echo '=== J/K/L prepare: Stage K mate eviction ===' >&2
set +e
PROFILE_FILE="$BASE_PROFILE_FILE" STAGE_F_ENV="$STAGE_F_ENV" STAGEJ_WINNER_ENV="$STAGEJ_WINNER_ENV" STAGEJ_PREPARE_ENV="$STAGEJ_PREPARE_ENV" ARCH="$ARCH" TARGET_MIB="$FORCED_TARGET_MIB" MAX_WINDOW="$BASE_MAXW" MOD="$BASE_PRIME" NGPU=8 \
  RUN_STAGED=1 PREPARE_ONLY=1 MIN_SPEEDUP="$STAGEK_MIN_SPEEDUP" EVICT_LIST="$MATE_EVICT_LIST" STAGED_PREFIX="$STAGEK_PREFIX" WINNER_ENV="$STAGEK_WINNER_ENV" RACE_PREFIX="$STAGEK_RACE_PREFIX" PREPARE_ENV="$STAGEK_PREPARE_ENV" \
  bash "$ONEESAN_ROOT/scripts/run/b300x8-nextgen-hybrid8-mate-evict-stagek-staged-fullprime-race.sh" 27
K_RC=$?
set -e
if ((K_RC==0)); then K_OK=1
elif ((K_RC==4)); then echo 'J/K/L prepare: Stage K rejected; use Stage J upstream' >&2
else exit "$K_RC"
fi
if ((K_OK)); then
  [[ -s "$STAGEK_PREPARE_ENV" && -s "$STAGEK_WINNER_ENV" ]] || exit 3
  # shellcheck disable=SC1090
  source "$STAGEK_PREPARE_ENV"
  [[ "${B300_STAGEK_PREPARED:-0}" == 1 && "${B300_STAGEK_PREPARED_MOD:-}" == "$BASE_PRIME" && -x "$B300_STAGEK_PREPARED_BIN" && -x "$B300_STAGEK_PREPARED_CONTROL_BIN" ]] || exit 3
  sha256sum -c "$B300_STAGEK_PREPARED_MANIFEST" >/dev/null || { echo 'Stage-K manifest failed in J/K/L prepare' >&2; exit 3; }
  UP_KIND=stagek; UP_PREP="$STAGEK_PREPARE_ENV"; UP_WINNER="$STAGEK_WINNER_ENV"; UP_BIN="$B300_STAGEK_PREPARED_BIN"; UP_LABEL="$B300_STAGEK_PREPARED_LABEL"; UP_THREADS="$B300_STAGEK_PREPARED_THREADS"; UP_CONTROL_BIN="$B300_STAGEK_PREPARED_CONTROL_BIN"; UP_CONTROL_LABEL="$B300_STAGEK_PREPARED_CONTROL_LABEL"; UP_CONTROL_THREADS="$B300_STAGEK_PREPARED_CONTROL_THREADS"; UP_MANIFEST="$B300_STAGEK_PREPARED_MANIFEST"
else
  UP_KIND=stagej; UP_PREP="$STAGEJ_PREPARE_ENV"; UP_WINNER="$STAGEJ_WINNER_ENV"; UP_BIN="$J_BIN"; UP_LABEL="$J_LABEL"; UP_THREADS="$J_THREADS"; UP_CONTROL_BIN="$J_CONTROL_BIN"; UP_CONTROL_LABEL="$J_CONTROL_LABEL"; UP_CONTROL_THREADS="$J_CONTROL_THREADS"; UP_MANIFEST="$B300_STAGEJ_PREPARED_MANIFEST"
fi
[[ -x "$UP_BIN" && -x "$UP_CONTROL_BIN" && -s "$UP_MANIFEST" ]] || exit 3

{
  printf 'B300_JKL_PREPARED=1\n'
  printf 'B300_JKL_REFINEMENT_APPLICABLE=1\n'
  printf 'B300_JKL_STAGEJ_OK=1\n'
  printf 'B300_JKL_STAGEK_OK=%q\n' "$K_OK"
  printf 'B300_JKL_STAGE_F_ENV=%q\n' "$STAGE_F_ENV"
  printf 'B300_JKL_BASE_SELECTED_ENV=%q\n' "$BASE_SELECTED_ENV"
  printf 'B300_JKL_BASE_BIN=%q\n' "$BASE_BIN"
  printf 'B300_JKL_BASE_BACKEND=%q\n' "$BASE_BACKEND"
  printf 'B300_JKL_BASE_PROFILE=%q\n' "$BASE_PROFILE"
  printf 'B300_JKL_BASE_RUNTIME=%q\n' "$BASE_RUNTIME"
  printf 'B300_JKL_BASE_THREADS=%q\n' "$BASE_THREADS"
  printf 'B300_JKL_BASE_HEAD_SHA=%q\n' "$BASE_HEAD"
  printf 'B300_JKL_BASE_HEAD_DIRTY=%q\n' "$BASE_DIRTY"
  printf 'B300_JKL_PROFILE_FILE=%q\n' "$BASE_PROFILE_FILE"
  printf 'B300_JKL_PROFILE_SHA256=%q\n' "$BASE_PROFILE_SHA"
  printf 'B300_JKL_SMOKE_PRIME=%q\n' "$BASE_PRIME"
  printf 'B300_JKL_MAX_WINDOW=%q\n' "$BASE_MAXW"
  printf 'B300_JKL_FORCED_TARGET_MIB=%q\n' "$FORCED_TARGET_MIB"
  printf 'B300_JKL_BUCKET_TARGET_MIB=%q\n' "$BUCKET_TARGET_MIB"
  printf 'B300_JKL_UPSTREAM_KIND=%q\n' "$UP_KIND"
  printf 'B300_JKL_UPSTREAM_PREPARE_ENV=%q\n' "$UP_PREP"
  printf 'B300_JKL_UPSTREAM_WINNER_ENV=%q\n' "$UP_WINNER"
  printf 'B300_JKL_UPSTREAM_BIN=%q\n' "$UP_BIN"
  printf 'B300_JKL_UPSTREAM_LABEL=%q\n' "$UP_LABEL"
  printf 'B300_JKL_UPSTREAM_THREADS=%q\n' "$UP_THREADS"
  printf 'B300_JKL_UPSTREAM_CONTROL_BIN=%q\n' "$UP_CONTROL_BIN"
  printf 'B300_JKL_UPSTREAM_CONTROL_LABEL=%q\n' "$UP_CONTROL_LABEL"
  printf 'B300_JKL_UPSTREAM_CONTROL_THREADS=%q\n' "$UP_CONTROL_THREADS"
  printf 'B300_JKL_UPSTREAM_MANIFEST=%q\n' "$UP_MANIFEST"
  printf 'B300_JKL_STAGEJ_PREPARE_ENV=%q\n' "$STAGEJ_PREPARE_ENV"
  printf 'B300_JKL_STAGEJ_WINNER_ENV=%q\n' "$STAGEJ_WINNER_ENV"
  printf 'B300_JKL_STAGEK_PREPARE_ENV=%q\n' "$STAGEK_PREPARE_ENV"
  printf 'B300_JKL_STAGEK_WINNER_ENV=%q\n' "$STAGEK_WINNER_ENV"
} >"$OUT_ENV"
cat "$OUT_ENV"
echo "b300x8-grand-jkl-prepare OK upstream=$UP_KIND stagek=$K_OK incumbent=$BASE_BACKEND prepared_env=$OUT_ENV no_refinement_fullprime=1" >&2
