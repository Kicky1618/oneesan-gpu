normalize_widths(){
  local raw="$1"; local out=() w old seen
  for w in $raw; do
    case "$w" in 1|2|4|8) ;; *) echo "bad width=$w" >&2; exit 2;; esac
    seen=0; for old in "${out[@]}"; do [[ "$old" == "$w" ]] && seen=1; done
    ((seen)) || out+=("$w")
  done
  ((${#out[@]})) || { echo 'width list must not be empty' >&2; exit 2; }
  printf '%s' "${out[*]}"
}
normalize_distances(){
  local raw="$1"; local out=() d old seen
  for d in $raw; do
    case "$d" in 1|2|4) ;; *) echo "bad distance=$d" >&2; exit 2;; esac
    seen=0; for old in "${out[@]}"; do [[ "$old" == "$d" ]] && seen=1; done
    ((seen)) || out+=("$d")
  done
  ((${#out[@]})) || { echo 'distance list must not be empty' >&2; exit 2; }
  printf '%s' "${out[*]}"
}
