#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"

N="${1:-27}"
if (( $# > 0 )); then shift; fi
[[ "$N" == 27 ]] || { echo 'joint next-self+hybrid8 selector targets n=27' >&2; exit 2; }

PROFILE_FILE="${PROFILE_FILE:-$ONEESAN_ROOT/work/b300_hbm_profile_refined21.env}"
ARCH="${ARCH:-native}"
MAX_WINDOW="${MAX_WINDOW:-14}"
PREFIX="${PREFIX:-$ONEESAN_ROOT/work/b300_joint_nextself_hybrid8_n27}"
JOINT_PREFIX="${JOINT_PREFIX:-${PREFIX}.joint}"
JOINT_PREPARE_ENV="${JOINT_PREPARE_ENV:-${PREFIX}.joint.prepared.env}"
NEXTSELF_PREFIX="${NEXTSELF_PREFIX:-${PREFIX}.nextself}"
NEXTSELF_WINNER_ENV="${NEXTSELF_WINNER_ENV:-${NEXTSELF_PREFIX}_winner.env}"
NEXTSELF_PREPARE_ENV="${NEXTSELF_PREPARE_ENV:-${PREFIX}.nextself.prepared.env}"
NEXTSELF_RACE_PREFIX="${NEXTSELF_RACE_PREFIX:-${PREFIX}.nextself.promote}"
HYBRID_PREFIX="${HYBRID_PREFIX:-${PREFIX}.hybrid8}"
HYBRID_WINNER_ENV="${HYBRID_WINNER_ENV:-${HYBRID_PREFIX}_winner.env}"
HYBRID_PREPARE_ENV="${HYBRID_PREPARE_ENV:-${PREFIX}.hybrid8.prepared.env}"
HYBRID_RACE_PREFIX="${HYBRID_RACE_PREFIX:-${PREFIX}.hybrid8.promote}"
HYBRID_NS_PREFIX="${HYBRID_NS_PREFIX:-${PREFIX}.hybrid8-nextself}"
HYBRID_NS_WINNER_ENV="${HYBRID_NS_WINNER_ENV:-${HYBRID_NS_PREFIX}_winner.env}"
HYBRID_NS_PREPARE_ENV="${HYBRID_NS_PREPARE_ENV:-${PREFIX}.hybrid8-nextself.prepared.env}"
HYBRID_NS_RACE_PREFIX="${HYBRID_NS_RACE_PREFIX:-${PREFIX}.hybrid8-nextself.promote}"
STAGEH_PREFIX="${STAGEH_PREFIX:-${PREFIX}.stageh-nextmate}"
STAGEH_WINNER_ENV="${STAGEH_WINNER_ENV:-${STAGEH_PREFIX}_winner.env}"
STAGEH_PREPARE_ENV="${STAGEH_PREPARE_ENV:-${PREFIX}.stageh-nextmate.prepared.env}"
STAGEH_RACE_PREFIX="${STAGEH_RACE_PREFIX:-${PREFIX}.stageh-nextmate.promote}"
RACE_PREFIX="${RACE_PREFIX:-${PREFIX}.race}"
SELECT_ONLY="${SELECT_ONLY:-1}"
REBUILD_BUCKETS="${REBUILD_BUCKETS:-1}"
RUN_NEXTSELF_STAGE="${RUN_NEXTSELF_STAGE:-1}"
RUN_HYBRID_STAGE="${RUN_HYBRID_STAGE:-1}"
RUN_HYBRID_NS_STAGE="${RUN_HYBRID_NS_STAGE:-1}"
RUN_STAGEH="${RUN_STAGEH:-1}"
NEXTSELF_THREADS="${NEXTSELF_THREADS:-256}"
NEXTSELF_MIN_SPEEDUP="${NEXTSELF_MIN_SPEEDUP:-1.01}"
NEXTSELF_SEARCH_ROWS="${NEXTSELF_SEARCH_ROWS:-1}"
NEXTSELF_VALIDATE_ROWS="${NEXTSELF_VALIDATE_ROWS:-4 8}"
NEXTSELF_SEARCH_REPEATS="${NEXTSELF_SEARCH_REPEATS:-1}"
NEXTSELF_VALIDATE_REPEATS="${NEXTSELF_VALIDATE_REPEATS:-1}"
HYBRID_MIN_SPEEDUP="${HYBRID_MIN_SPEEDUP:-1.01}"
HYBRID_NS_MIN_SPEEDUP="${HYBRID_NS_MIN_SPEEDUP:-1.01}"
HYBRID_NS_WIDTH_LIST="${HYBRID_NS_WIDTH_LIST:-1 2 4 8}"
HYBRID_NS_DISTANCE_LIST="${HYBRID_NS_DISTANCE_LIST:-1 2 4}"
HYBRID_NS_SEARCH_REPEATS="${HYBRID_NS_SEARCH_REPEATS:-1}"
HYBRID_NS_VALIDATE_REPEATS="${HYBRID_NS_VALIDATE_REPEATS:-1}"
STAGEH_MIN_SPEEDUP="${STAGEH_MIN_SPEEDUP:-1.002}"

for x in SELECT_ONLY REBUILD_BUCKETS RUN_NEXTSELF_STAGE RUN_HYBRID_STAGE RUN_HYBRID_NS_STAGE RUN_STAGEH; do
  v="${!x}"
  [[ "$v" == 0 || "$v" == 1 ]] || { echo "$x must be 0/1" >&2; exit 2; }
done
for x in NEXTSELF_SEARCH_REPEATS NEXTSELF_VALIDATE_REPEATS HYBRID_NS_SEARCH_REPEATS HYBRID_NS_VALIDATE_REPEATS; do
  v="${!x}"
  [[ "$v" =~ ^[1-9][0-9]*$ ]] || { echo "$x must be >=1" >&2; exit 2; }
done
python3 - "$NEXTSELF_MIN_SPEEDUP" "$HYBRID_MIN_SPEEDUP" "$HYBRID_NS_MIN_SPEEDUP" "$STAGEH_MIN_SPEEDUP" <<'PY'
import sys
for name,v in zip(('NEXTSELF_MIN_SPEEDUP','HYBRID_MIN_SPEEDUP','HYBRID_NS_MIN_SPEEDUP','STAGEH_MIN_SPEEDUP'),map(float,sys.argv[1:])):
    if v < 1.0: raise SystemExit(f'{name} must be >=1')
PY
widths=()
for w in $HYBRID_NS_WIDTH_LIST; do case "$w" in 1|2|4|8) ;; *) echo "bad HYBRID_NS_WIDTH_LIST entry=$w" >&2; exit 2;; esac; seen=0; for old in "${widths[@]}"; do [[ "$old" == "$w" ]] && seen=1; done; ((seen)) || widths+=("$w"); done
((${#widths[@]})) || { echo 'HYBRID_NS_WIDTH_LIST must not be empty' >&2; exit 2; }
HYBRID_NS_WIDTH_LIST="${widths[*]}"
distances=()
for d in $HYBRID_NS_DISTANCE_LIST; do case "$d" in 1|2|4) ;; *) echo "bad HYBRID_NS_DISTANCE_LIST entry=$d" >&2; exit 2;; esac; seen=0; for old in "${distances[@]}"; do [[ "$old" == "$d" ]] && seen=1; done; ((seen)) || distances+=("$d"); done
((${#distances[@]})) || { echo 'HYBRID_NS_DISTANCE_LIST must not be empty' >&2; exit 2; }
HYBRID_NS_DISTANCE_LIST="${distances[*]}"
[[ "$NEXTSELF_THREADS" =~ ^[0-9]+$ ]] && (( NEXTSELF_THREADS >= 32 && NEXTSELF_THREADS <= 768 && NEXTSELF_THREADS % 32 == 0 )) || {
  echo 'NEXTSELF_THREADS must be warp multiple 32..768' >&2; exit 2;
}
[[ "$MAX_WINDOW" =~ ^[1-9][0-9]*$ ]] || { echo 'MAX_WINDOW must be positive integer' >&2; exit 2; }
[[ -f "$PROFILE_FILE" ]] || { echo "missing profile: $PROFILE_FILE" >&2; exit 2; }
mkdir -p \
  "$(dirname "$JOINT_PREPARE_ENV")" \
  "$(dirname "$NEXTSELF_PREPARE_ENV")" \
  "$(dirname "$HYBRID_PREPARE_ENV")" \
  "$(dirname "$HYBRID_NS_PREPARE_ENV")" \
  "$(dirname "$STAGEH_PREPARE_ENV")" \
  "$(dirname "$RACE_PREFIX")"

echo '=== grand selector: prepare calibrated joint forced candidates and profiled buckets ===' >&2
PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" MAX_WINDOW="$MAX_WINDOW" PREFIX="$JOINT_PREFIX" PREPARE_ONLY=1 PREPARE_ENV="$JOINT_PREPARE_ENV" \
  SELECT_ONLY=1 REBUILD_BUCKETS="$REBUILD_BUCKETS" \
  bash "$ONEESAN_ROOT/scripts/run/b300x8-joint-calibrated-select.sh" 27
[[ -s "$JOINT_PREPARE_ENV" ]] || { echo "joint prepare env missing: $JOINT_PREPARE_ENV" >&2; exit 3; }
# shellcheck disable=SC1090
source "$JOINT_PREPARE_ENV"
[[ "${B300_JOINT_PREPARED:-0}" == 1 ]] || { echo 'joint prepared marker missing' >&2; exit 3; }
[[ -x "$FORCED_OVERRIDE_BIN" ]] || { echo 'prepared joint primary missing' >&2; exit 3; }
JOINT_PRIMARY_BIN="$FORCED_OVERRIDE_BIN"
JOINT_PRIMARY_LABEL="$FORCED_OVERRIDE_LABEL"
JOINT_PRIMARY_THREADS="$FORCED_OVERRIDE_THREADS"
JOINT_BASE_BIN="${FORCED_BASE_BIN:-}"
JOINT_BASE_LABEL="${FORCED_BASE_LABEL:-}"
JOINT_BASE_THREADS="${FORCED_BASE_THREADS:-256}"
TARGET_MIB="$FORCED_TARGET_MIB"
PRIME="$SMOKE_PRIME"
MAX_WINDOW="${MAX_WINDOW:-14}"

NEXTSELF_OK=0
NEXTSELF_RC=0
echo '=== grand selector: stage/prepare next-self ===' >&2
set +e
MOD="$PRIME" PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" \
  GRIDFP_THREADS="$NEXTSELF_THREADS" RUN_STAGED="$RUN_NEXTSELF_STAGE" PREPARE_ONLY=1 \
  SEARCH_ROWS="$NEXTSELF_SEARCH_ROWS" VALIDATE_ROWS="$NEXTSELF_VALIDATE_ROWS" \
  SEARCH_REPEATS="$NEXTSELF_SEARCH_REPEATS" VALIDATE_REPEATS="$NEXTSELF_VALIDATE_REPEATS" MIN_SPEEDUP="$NEXTSELF_MIN_SPEEDUP" \
  STAGED_PREFIX="$NEXTSELF_PREFIX" WINNER_ENV="$NEXTSELF_WINNER_ENV" RACE_PREFIX="$NEXTSELF_RACE_PREFIX" PREPARE_ENV="$NEXTSELF_PREPARE_ENV" \
  bash "$ONEESAN_ROOT/scripts/run/b300x8-ilp8-nextself-staged-fullprime-race.sh" 27
NEXTSELF_RC=$?
set -e
if (( NEXTSELF_RC == 0 )); then
  [[ -s "$NEXTSELF_PREPARE_ENV" ]] || { echo 'next-self prepare env missing after success' >&2; exit 3; }
  # shellcheck disable=SC1090
  source "$NEXTSELF_PREPARE_ENV"
  [[ "${B300_NEXTSELF_PREPARED:-0}" == 1 ]] || { echo 'next-self prepared marker missing' >&2; exit 3; }
  [[ -x "$B300_NEXTSELF_PREPARED_BIN" && -x "$B300_NEXTSELF_PREPARED_CONTROL_BIN" ]] || { echo 'next-self prepared binaries missing' >&2; exit 3; }
  NEXTSELF_OK=1
elif (( NEXTSELF_RC == 4 )); then
  echo 'grand selector: next-self rejected by staged gates' >&2
else
  echo "grand selector: next-self preparation failed rc=$NEXTSELF_RC" >&2
  exit "$NEXTSELF_RC"
fi

HYBRID_OK=0
HYBRID_RC=0
echo '=== grand selector: stage/prepare nextgen hybrid8 ===' >&2
set +e
MOD="$PRIME" PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" \
  RUN_STAGED="$RUN_HYBRID_STAGE" PREPARE_ONLY=1 HYBRID_MIN_SPEEDUP="$HYBRID_MIN_SPEEDUP" \
  STAGED_PREFIX="$HYBRID_PREFIX" WINNER_ENV="$HYBRID_WINNER_ENV" RACE_PREFIX="$HYBRID_RACE_PREFIX" PREPARE_ENV="$HYBRID_PREPARE_ENV" \
  bash "$ONEESAN_ROOT/scripts/run/b300x8-nextgen-hybrid8-staged-fullprime-race.sh" 27
HYBRID_RC=$?
set -e
if (( HYBRID_RC == 0 )); then
  [[ -s "$HYBRID_PREPARE_ENV" ]] || { echo 'hybrid8 prepare env missing after success' >&2; exit 3; }
  # shellcheck disable=SC1090
  source "$HYBRID_PREPARE_ENV"
  [[ "${B300_HYBRID8_PREPARED:-0}" == 1 ]] || { echo 'hybrid8 prepared marker missing' >&2; exit 3; }
  [[ -x "$B300_HYBRID8_PREPARED_BIN" && -x "$B300_HYBRID8_PREPARED_BASE_BIN" ]] || { echo 'hybrid8 prepared binaries missing' >&2; exit 3; }
  HYBRID_OK=1
elif (( HYBRID_RC == 4 )); then
  echo 'grand selector: hybrid8 rejected by staged gates' >&2
else
  echo "grand selector: hybrid8 preparation failed rc=$HYBRID_RC" >&2
  exit "$HYBRID_RC"
fi

HYBRID_NS_OK=0
HYBRID_NS_RC=0
if (( HYBRID_OK )); then
  echo "=== grand selector: stage/prepare hybrid8 + next-self geometry widths=[$HYBRID_NS_WIDTH_LIST] distances=[$HYBRID_NS_DISTANCE_LIST] ===" >&2
  set +e
  MOD="$PRIME" PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" \
    RUN_STAGED="$RUN_HYBRID_NS_STAGE" RUN_HYBRID_STAGE=0 PREPARE_ONLY=1 MIN_SPEEDUP="$HYBRID_NS_MIN_SPEEDUP" \
    WIDTH_LIST="$HYBRID_NS_WIDTH_LIST" DISTANCE_LIST="$HYBRID_NS_DISTANCE_LIST" \
    SEARCH_REPEATS="$HYBRID_NS_SEARCH_REPEATS" VALIDATE_REPEATS="$HYBRID_NS_VALIDATE_REPEATS" \
    STAGED_PREFIX="$HYBRID_NS_PREFIX" HYBRID_PREFIX="$HYBRID_PREFIX" HYBRID_WINNER_ENV="$HYBRID_WINNER_ENV" \
    WINNER_ENV="$HYBRID_NS_WINNER_ENV" RACE_PREFIX="$HYBRID_NS_RACE_PREFIX" PREPARE_ENV="$HYBRID_NS_PREPARE_ENV" \
    bash "$ONEESAN_ROOT/scripts/run/b300x8-nextgen-hybrid8-nextself-staged-fullprime-race.sh" 27
  HYBRID_NS_RC=$?
  set -e
  if (( HYBRID_NS_RC == 0 )); then
    [[ -s "$HYBRID_NS_PREPARE_ENV" ]] || { echo 'hybrid8 next-self prepare env missing after success' >&2; exit 3; }
    # shellcheck disable=SC1090
    source "$HYBRID_NS_PREPARE_ENV"
    [[ "${B300_HYBRID8_NEXTSELF_PREPARED:-0}" == 1 ]] || { echo 'hybrid8 next-self prepared marker missing' >&2; exit 3; }
    [[ -x "$B300_HYBRID8_NEXTSELF_PREPARED_BIN" && -x "$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_BIN" ]] || { echo 'hybrid8 next-self prepared binaries missing' >&2; exit 3; }
    case "${B300_HYBRID8_NEXTSELF_PREPARED_WIDTH:-}" in 1|2|4|8) ;; *) echo 'hybrid8 next-self prepared width missing/invalid' >&2; exit 3;; esac
    case "${B300_HYBRID8_NEXTSELF_PREPARED_DISTANCE:-}" in 1|2|4) ;; *) echo 'hybrid8 next-self prepared distance missing/invalid' >&2; exit 3;; esac
    HYBRID_NS_OK=1
  elif (( HYBRID_NS_RC == 4 )); then
    echo 'grand selector: hybrid8 next-self rejected by staged gates' >&2
  else
    echo "grand selector: hybrid8 next-self preparation failed rc=$HYBRID_NS_RC" >&2
    exit "$HYBRID_NS_RC"
  fi
fi

STAGEH_OK=0
STAGEH_RC=0
if (( HYBRID_NS_OK )); then
  echo "=== grand selector: stage/prepare next-mate on w${B300_HYBRID8_NEXTSELF_PREPARED_WIDTH}d${B300_HYBRID8_NEXTSELF_PREPARED_DISTANCE} ===" >&2
  set +e
  PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" MOD="$PRIME" \
    INPUT_ENV="$HYBRID_NS_WINNER_ENV" RUN_STAGED="$RUN_STAGEH" PREPARE_ONLY=1 MIN_SPEEDUP="$STAGEH_MIN_SPEEDUP" \
    STAGED_PREFIX="$STAGEH_PREFIX" WINNER_ENV="$STAGEH_WINNER_ENV" RACE_PREFIX="$STAGEH_RACE_PREFIX" PREPARE_ENV="$STAGEH_PREPARE_ENV" \
    bash "$ONEESAN_ROOT/scripts/run/b300x8-nextgen-hybrid8-nextmate-staged-fullprime-race.sh" 27
  STAGEH_RC=$?
  set -e
  if (( STAGEH_RC == 0 )); then
    [[ -s "$STAGEH_PREPARE_ENV" ]] || { echo 'Stage-H prepare env missing after success' >&2; exit 3; }
    # shellcheck disable=SC1090
    source "$STAGEH_PREPARE_ENV"
    [[ "${B300_STAGEH_PREPARED:-0}" == 1 ]] || { echo 'Stage-H prepared marker missing' >&2; exit 3; }
    [[ -x "$B300_STAGEH_PREPARED_BIN" && -x "$B300_STAGEH_PREPARED_CONTROL_BIN" ]] || { echo 'Stage-H prepared binaries missing' >&2; exit 3; }
    [[ "$B300_STAGEH_PREPARED_WIDTH" == "$B300_HYBRID8_NEXTSELF_PREPARED_WIDTH" && "$B300_STAGEH_PREPARED_DISTANCE" == "$B300_HYBRID8_NEXTSELF_PREPARED_DISTANCE" ]] || {
      echo 'Stage-H prepared geometry does not match Stage-F geometry' >&2; exit 3;
    }
    STAGEH_OK=1
  elif (( STAGEH_RC == 4 )); then
    echo 'grand selector: Stage-H next-mate rejected by staged gates' >&2
  else
    echo "grand selector: Stage-H next-mate preparation failed rc=$STAGEH_RC" >&2
    exit "$STAGEH_RC"
  fi
fi

# Five forced-like slots plus profiled warp/orbit = seven total. Stage H uses
# the same selected geometry as Stage F, so its self control represents the
# geometry candidate without consuming an additional slot.
P_BIN=""; P_LABEL=""; P_THREADS=256
B_BIN=""; B_LABEL=""; B_THREADS=256
E1_BIN=""; E1_LABEL=""; E1_THREADS=256
E2_BIN=""; E2_LABEL=""; E2_THREADS=256
E3_BIN=""; E3_LABEL=""; E3_THREADS=256
MODE=""

if (( STAGEH_OK && NEXTSELF_OK )); then
  MODE=stageh_nextmate_grand
  P_BIN="$B300_STAGEH_PREPARED_BIN"; P_LABEL="$B300_STAGEH_PREPARED_LABEL"; P_THREADS="$B300_STAGEH_PREPARED_THREADS"
  B_BIN="$B300_STAGEH_PREPARED_CONTROL_BIN"; B_LABEL="$B300_STAGEH_PREPARED_CONTROL_LABEL"; B_THREADS="$B300_STAGEH_PREPARED_CONTROL_THREADS"
  E1_BIN="$B300_HYBRID8_PREPARED_BASE_BIN"; E1_LABEL="$B300_HYBRID8_PREPARED_BASE_LABEL"; E1_THREADS="$B300_HYBRID8_PREPARED_BASE_THREADS"
  E2_BIN="$B300_NEXTSELF_PREPARED_BIN"; E2_LABEL="$B300_NEXTSELF_PREPARED_LABEL"; E2_THREADS="$B300_NEXTSELF_PREPARED_THREADS"
  E3_BIN="$JOINT_PRIMARY_BIN"; E3_LABEL="$JOINT_PRIMARY_LABEL"; E3_THREADS="$JOINT_PRIMARY_THREADS"
elif (( STAGEH_OK )); then
  MODE=stageh_nextmate_joint
  P_BIN="$B300_STAGEH_PREPARED_BIN"; P_LABEL="$B300_STAGEH_PREPARED_LABEL"; P_THREADS="$B300_STAGEH_PREPARED_THREADS"
  B_BIN="$B300_STAGEH_PREPARED_CONTROL_BIN"; B_LABEL="$B300_STAGEH_PREPARED_CONTROL_LABEL"; B_THREADS="$B300_STAGEH_PREPARED_CONTROL_THREADS"
  E1_BIN="$B300_HYBRID8_PREPARED_BASE_BIN"; E1_LABEL="$B300_HYBRID8_PREPARED_BASE_LABEL"; E1_THREADS="$B300_HYBRID8_PREPARED_BASE_THREADS"
  E2_BIN="$JOINT_PRIMARY_BIN"; E2_LABEL="$JOINT_PRIMARY_LABEL"; E2_THREADS="$JOINT_PRIMARY_THREADS"
  if [[ -n "$JOINT_BASE_BIN" && "$JOINT_BASE_BIN" != "$JOINT_PRIMARY_BIN" ]]; then E3_BIN="$JOINT_BASE_BIN"; E3_LABEL="$JOINT_BASE_LABEL"; E3_THREADS="$JOINT_BASE_THREADS"; fi
elif (( HYBRID_NS_OK && NEXTSELF_OK )); then
  MODE=hybrid8_nextself_composed_grand
  P_BIN="$B300_HYBRID8_NEXTSELF_PREPARED_BIN"; P_LABEL="$B300_HYBRID8_NEXTSELF_PREPARED_LABEL"; P_THREADS="$B300_HYBRID8_NEXTSELF_PREPARED_THREADS"
  B_BIN="$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_BIN"; B_LABEL="$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_LABEL"; B_THREADS="$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_THREADS"
  E1_BIN="$B300_HYBRID8_PREPARED_BASE_BIN"; E1_LABEL="$B300_HYBRID8_PREPARED_BASE_LABEL"; E1_THREADS="$B300_HYBRID8_PREPARED_BASE_THREADS"
  E2_BIN="$B300_NEXTSELF_PREPARED_BIN"; E2_LABEL="$B300_NEXTSELF_PREPARED_LABEL"; E2_THREADS="$B300_NEXTSELF_PREPARED_THREADS"
  E3_BIN="$JOINT_PRIMARY_BIN"; E3_LABEL="$JOINT_PRIMARY_LABEL"; E3_THREADS="$JOINT_PRIMARY_THREADS"
elif (( HYBRID_NS_OK )); then
  MODE=hybrid8_nextself_composed_joint
  P_BIN="$B300_HYBRID8_NEXTSELF_PREPARED_BIN"; P_LABEL="$B300_HYBRID8_NEXTSELF_PREPARED_LABEL"; P_THREADS="$B300_HYBRID8_NEXTSELF_PREPARED_THREADS"
  B_BIN="$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_BIN"; B_LABEL="$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_LABEL"; B_THREADS="$B300_HYBRID8_NEXTSELF_PREPARED_CONTROL_THREADS"
  E1_BIN="$B300_HYBRID8_PREPARED_BASE_BIN"; E1_LABEL="$B300_HYBRID8_PREPARED_BASE_LABEL"; E1_THREADS="$B300_HYBRID8_PREPARED_BASE_THREADS"
  E2_BIN="$JOINT_PRIMARY_BIN"; E2_LABEL="$JOINT_PRIMARY_LABEL"; E2_THREADS="$JOINT_PRIMARY_THREADS"
  if [[ -n "$JOINT_BASE_BIN" && "$JOINT_BASE_BIN" != "$JOINT_PRIMARY_BIN" ]]; then E3_BIN="$JOINT_BASE_BIN"; E3_LABEL="$JOINT_BASE_LABEL"; E3_THREADS="$JOINT_BASE_THREADS"; fi
elif (( NEXTSELF_OK && HYBRID_OK )); then
  MODE=nextself_hybrid8_joint
  P_BIN="$B300_NEXTSELF_PREPARED_BIN"; P_LABEL="$B300_NEXTSELF_PREPARED_LABEL"; P_THREADS="$B300_NEXTSELF_PREPARED_THREADS"
  B_BIN="$B300_NEXTSELF_PREPARED_CONTROL_BIN"; B_LABEL="$B300_NEXTSELF_PREPARED_CONTROL_LABEL"; B_THREADS="$B300_NEXTSELF_PREPARED_CONTROL_THREADS"
  E1_BIN="$B300_HYBRID8_PREPARED_BIN"; E1_LABEL="$B300_HYBRID8_PREPARED_LABEL"; E1_THREADS="$B300_HYBRID8_PREPARED_THREADS"
  E2_BIN="$B300_HYBRID8_PREPARED_BASE_BIN"; E2_LABEL="$B300_HYBRID8_PREPARED_BASE_LABEL"; E2_THREADS="$B300_HYBRID8_PREPARED_BASE_THREADS"
  E3_BIN="$JOINT_PRIMARY_BIN"; E3_LABEL="$JOINT_PRIMARY_LABEL"; E3_THREADS="$JOINT_PRIMARY_THREADS"
elif (( NEXTSELF_OK )); then
  MODE=nextself_joint
  P_BIN="$B300_NEXTSELF_PREPARED_BIN"; P_LABEL="$B300_NEXTSELF_PREPARED_LABEL"; P_THREADS="$B300_NEXTSELF_PREPARED_THREADS"
  B_BIN="$B300_NEXTSELF_PREPARED_CONTROL_BIN"; B_LABEL="$B300_NEXTSELF_PREPARED_CONTROL_LABEL"; B_THREADS="$B300_NEXTSELF_PREPARED_CONTROL_THREADS"
  E1_BIN="$JOINT_PRIMARY_BIN"; E1_LABEL="$JOINT_PRIMARY_LABEL"; E1_THREADS="$JOINT_PRIMARY_THREADS"
  if [[ -n "$JOINT_BASE_BIN" && "$JOINT_BASE_BIN" != "$JOINT_PRIMARY_BIN" ]]; then E2_BIN="$JOINT_BASE_BIN"; E2_LABEL="$JOINT_BASE_LABEL"; E2_THREADS="$JOINT_BASE_THREADS"; fi
elif (( HYBRID_OK )); then
  MODE=hybrid8_joint
  P_BIN="$B300_HYBRID8_PREPARED_BIN"; P_LABEL="$B300_HYBRID8_PREPARED_LABEL"; P_THREADS="$B300_HYBRID8_PREPARED_THREADS"
  B_BIN="$B300_HYBRID8_PREPARED_BASE_BIN"; B_LABEL="$B300_HYBRID8_PREPARED_BASE_LABEL"; B_THREADS="$B300_HYBRID8_PREPARED_BASE_THREADS"
  E1_BIN="$JOINT_PRIMARY_BIN"; E1_LABEL="$JOINT_PRIMARY_LABEL"; E1_THREADS="$JOINT_PRIMARY_THREADS"
  if [[ -n "$JOINT_BASE_BIN" && "$JOINT_BASE_BIN" != "$JOINT_PRIMARY_BIN" ]]; then E2_BIN="$JOINT_BASE_BIN"; E2_LABEL="$JOINT_BASE_LABEL"; E2_THREADS="$JOINT_BASE_THREADS"; fi
else
  MODE=joint_fallback
  P_BIN="$JOINT_PRIMARY_BIN"; P_LABEL="$JOINT_PRIMARY_LABEL"; P_THREADS="$JOINT_PRIMARY_THREADS"
  if [[ -n "$JOINT_BASE_BIN" && "$JOINT_BASE_BIN" != "$JOINT_PRIMARY_BIN" ]]; then B_BIN="$JOINT_BASE_BIN"; B_LABEL="$JOINT_BASE_LABEL"; B_THREADS="$JOINT_BASE_THREADS"; fi
fi

[[ -n "$P_BIN" && -x "$P_BIN" ]] || { echo 'grand selector primary candidate missing' >&2; exit 3; }
for t in "$P_THREADS" "$B_THREADS" "$E1_THREADS" "$E2_THREADS" "$E3_THREADS"; do
  [[ "$t" =~ ^[0-9]+$ ]] && ((t>=32 && t<=1024 && t%32==0)) || { echo "bad candidate threads=$t" >&2; exit 3; }
done

SUMMARY_ENV="${RACE_PREFIX}_grand.env"
DROP_JOINT_BASE=0
DROP_NEXTSELF_CONTROL=0
case "$MODE" in nextself_hybrid8_joint|hybrid8_nextself_composed_grand|stageh_nextmate_grand) DROP_JOINT_BASE=1;; esac
case "$MODE" in hybrid8_nextself_composed_grand|stageh_nextmate_grand) DROP_NEXTSELF_CONTROL=1;; esac
{
  printf 'B300_GRAND_PREPARED=1\n'
  printf 'B300_GRAND_MODE=%q\n' "$MODE"
