#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/../lib/common.sh"
N="${1:-27}"; if (($#>0)); then shift; fi
[[ "$N" == 27 ]] || exit 2
PROFILE_FILE="${PROFILE_FILE:-$ONEESAN_ROOT/work/b300_hbm_profile_refined21.env}"; [[ -f "$PROFILE_FILE" ]] || exit 2
ARCH="${ARCH:-native}"; TARGET_MIB="${TARGET_MIB:-65536}"; MAX_WINDOW="${MAX_WINDOW:-14}"
INPUT_ENV="${INPUT_ENV:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextself_staged_winner.env}"
SELF_EVICT="${SELF_EVICT:-default}"
RUN_STAGED="${RUN_STAGED:-1}"; PREPARE_ONLY="${PREPARE_ONLY:-0}"; SELECT_ONLY="${SELECT_ONLY:-1}"; REBUILD_BUCKETS="${REBUILD_BUCKETS:-1}"; MIN_SPEEDUP="${MIN_SPEEDUP:-1.002}"
STAGED_PREFIX="${STAGED_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextmate_staged}"; WINNER_ENV="${WINNER_ENV:-${STAGED_PREFIX}_winner.env}"; MANIFEST="${MANIFEST:-${WINNER_ENV%.env}_promotion-inputs.sha256}"
RACE_PREFIX="${RACE_PREFIX:-$ONEESAN_ROOT/work/b300_nextgen_hybrid8_nextmate_fullprime_n27}"; PREPARE_ENV="${PREPARE_ENV:-${RACE_PREFIX}_prepared.env}"
for x in RUN_STAGED PREPARE_ONLY SELECT_ONLY REBUILD_BUCKETS; do v="${!x}"; [[ "$v" == 0 || "$v" == 1 ]] || exit 2; done
case "$SELF_EVICT" in default|normal|last) ;; *) echo 'SELF_EVICT must be default,normal,last' >&2; exit 2;; esac
command -v sha256sum >/dev/null || exit 2
if [[ "$RUN_STAGED" == 1 ]]; then
  INPUT_ENV="$INPUT_ENV" SELF_EVICT="$SELF_EVICT" ARCH="$ARCH" MOD="${MOD:-4294967291}" TARGET_MIB="$TARGET_MIB" MAX_WINDOW="$MAX_WINDOW" MIN_SPEEDUP="$MIN_SPEEDUP" PREFIX="$STAGED_PREFIX" FINAL_ENV="$WINNER_ENV" \
    bash "$ONEESAN_ROOT/scripts/bench/b300-nextgen-hybrid8-nextmate-staged-calibrate.sh"
fi
[[ -s "$WINNER_ENV" ]] || exit 3
# shellcheck disable=SC1090
source "$WINNER_ENV"
for k in B300_STAGEH_STAGED_VALIDATED B300_STAGEH_FINAL_ENABLED B300_STAGEH_FINAL_WIDTH B300_STAGEH_FINAL_DISTANCE B300_STAGEH_FINAL_SELF_EVICT B300_STAGEH_FINAL_BIN B300_STAGEH_FINAL_THREADS B300_STAGEH_FINAL_WALL_S B300_STAGEH_FINAL_HIGH_S B300_STAGEH_FINAL_SPEEDUP_VS_SELF B300_STAGEH_FINAL_SPILL_FREE B300_STAGEH_CONTROL_BIN B300_STAGEH_CONTROL_THREADS B300_STAGEH_FINAL_STAGE_ROWS B300_STAGEH_FINAL_STAGE_RESIDUE B300_STAGEH_INPUT_STAGE_F_ENV; do [[ -n "${!k+x}" ]] || { echo "Stage-H env missing $k" >&2; exit 3; }; done
[[ "$B300_STAGEH_STAGED_VALIDATED" == 1 && "$B300_STAGEH_FINAL_ENABLED" == 1 && "$B300_STAGEH_FINAL_SPILL_FREE" == 1 ]] || { echo 'Stage H not promotable' >&2; exit 4; }
case "$B300_STAGEH_FINAL_WIDTH" in 1|2|4|8);;*) exit 3;; esac; case "$B300_STAGEH_FINAL_DISTANCE" in 1|2|4);;*) exit 3;; esac
case "$B300_STAGEH_FINAL_SELF_EVICT" in default|normal|last) ;; *) exit 3;; esac
[[ "$B300_STAGEH_FINAL_SELF_EVICT" == "$SELF_EVICT" ]] || { echo 'Stage-H self eviction differs from requested value' >&2; exit 3; }
for k in B300_STAGEH_FINAL_THREADS B300_STAGEH_CONTROL_THREADS; do v="${!k}"; [[ "$v" =~ ^[0-9]+$ ]] && ((v>=32&&v<=1024&&v%32==0)) || exit 3; done
[[ -x "$B300_STAGEH_FINAL_BIN" && -x "$B300_STAGEH_CONTROL_BIN" && -s "$B300_STAGEH_INPUT_STAGE_F_ENV" ]] || exit 3
python3 - "$B300_STAGEH_FINAL_SPEEDUP_VS_SELF" "$MIN_SPEEDUP" <<'PY'
import sys
if float(sys.argv[1]) < float(sys.argv[2]): raise SystemExit('Stage-H speedup gate failed')
PY
if [[ "$RUN_STAGED" == 1 ]]; then
  tmp="${MANIFEST}.tmp"; mkdir -p "$(dirname "$MANIFEST")"
  sha256sum "$WINNER_ENV" "$B300_STAGEH_INPUT_STAGE_F_ENV" "$B300_STAGEH_FINAL_BIN" "$B300_STAGEH_CONTROL_BIN" >"$tmp"; mv "$tmp" "$MANIFEST"
else
  [[ -s "$MANIFEST" ]] || exit 3
fi
sha256sum -c "$MANIFEST" >/dev/null || { echo 'Stage-H fingerprint mismatch' >&2; exit 3; }
FINAL_SHA="$(sha256sum "$B300_STAGEH_FINAL_BIN" | awk '{print $1}')"; CONTROL_SHA="$(sha256sum "$B300_STAGEH_CONTROL_BIN" | awk '{print $1}')"; MANIFEST_SHA="$(sha256sum "$MANIFEST" | awk '{print $1}')"
PROMOTION_ENV="${RACE_PREFIX}_promotion.env"
cat >"$PROMOTION_ENV" <<EOF
B300_STAGEH_PROMOTION_VALIDATED=1
B300_STAGEH_PROMOTION_WIDTH=$B300_STAGEH_FINAL_WIDTH
B300_STAGEH_PROMOTION_DISTANCE=$B300_STAGEH_FINAL_DISTANCE
B300_STAGEH_PROMOTION_SELF_EVICT=$B300_STAGEH_FINAL_SELF_EVICT
B300_STAGEH_PROMOTION_BIN=$(printf '%q' "$B300_STAGEH_FINAL_BIN")
B300_STAGEH_PROMOTION_BIN_SHA256=$FINAL_SHA
B300_STAGEH_PROMOTION_CONTROL_BIN=$(printf '%q' "$B300_STAGEH_CONTROL_BIN")
B300_STAGEH_PROMOTION_CONTROL_SHA256=$CONTROL_SHA
B300_STAGEH_PROMOTION_MANIFEST=$(printf '%q' "$MANIFEST")
B300_STAGEH_PROMOTION_MANIFEST_SHA256=$MANIFEST_SHA
B300_STAGEH_PROMOTION_STAGE_ROWS=$B300_STAGEH_FINAL_STAGE_ROWS
B300_STAGEH_PROMOTION_STAGE_RESIDUE=$B300_STAGEH_FINAL_STAGE_RESIDUE
B300_STAGEH_PROMOTION_SPEEDUP=$B300_STAGEH_FINAL_SPEEDUP_VS_SELF
B300_STAGEH_PROMOTION_HIGH_S=$B300_STAGEH_FINAL_HIGH_S
EOF
label="nextgen_hybrid8_nextself_mate_w${B300_STAGEH_FINAL_WIDTH}_d${B300_STAGEH_FINAL_DISTANCE}_sev${B300_STAGEH_FINAL_SELF_EVICT}"
control_label="nextgen_hybrid8_nextself_self_w${B300_STAGEH_FINAL_WIDTH}_d${B300_STAGEH_FINAL_DISTANCE}_ev${B300_STAGEH_FINAL_SELF_EVICT}"
if [[ "$PREPARE_ONLY" == 1 ]]; then
  {
    printf 'B300_STAGEH_PREPARED=1\n'
    printf 'B300_STAGEH_PREPARED_WIDTH=%q\n' "$B300_STAGEH_FINAL_WIDTH"
    printf 'B300_STAGEH_PREPARED_DISTANCE=%q\n' "$B300_STAGEH_FINAL_DISTANCE"
    printf 'B300_STAGEH_PREPARED_SELF_EVICT=%q\n' "$B300_STAGEH_FINAL_SELF_EVICT"
    printf 'B300_STAGEH_PREPARED_BIN=%q\n' "$B300_STAGEH_FINAL_BIN"
    printf 'B300_STAGEH_PREPARED_LABEL=%q\n' "$label"
    printf 'B300_STAGEH_PREPARED_THREADS=%q\n' "$B300_STAGEH_FINAL_THREADS"
    printf 'B300_STAGEH_PREPARED_CONTROL_BIN=%q\n' "$B300_STAGEH_CONTROL_BIN"
    printf 'B300_STAGEH_PREPARED_CONTROL_LABEL=%q\n' "$control_label"
    printf 'B300_STAGEH_PREPARED_CONTROL_THREADS=%q\n' "$B300_STAGEH_CONTROL_THREADS"
    printf 'B300_STAGEH_PREPARED_SPEEDUP=%q\n' "$B300_STAGEH_FINAL_SPEEDUP_VS_SELF"
    printf 'B300_STAGEH_PREPARED_HIGH_S=%q\n' "$B300_STAGEH_FINAL_HIGH_S"
    printf 'B300_STAGEH_PREPARED_MANIFEST=%q\n' "$MANIFEST"
    printf 'B300_STAGEH_PREPARED_PROMOTION_ENV=%q\n' "$PROMOTION_ENV"
  } >"$PREPARE_ENV"
  cat "$PREPARE_ENV"
  echo "STAGE H PREPARED width=$B300_STAGEH_FINAL_WIDTH distance=$B300_STAGEH_FINAL_DISTANCE self_evict=$B300_STAGEH_FINAL_SELF_EVICT speedup=${B300_STAGEH_FINAL_SPEEDUP_VS_SELF}x high_s=$B300_STAGEH_FINAL_HIGH_S" >&2
  exit 0
fi
exec env PROFILE_FILE="$PROFILE_FILE" ARCH="$ARCH" MAX_WINDOW="$MAX_WINDOW" FORCED_TARGET_MIB="$TARGET_MIB" \
 FORCED_OVERRIDE_BIN="$B300_STAGEH_FINAL_BIN" FORCED_OVERRIDE_LABEL="$label" FORCED_OVERRIDE_THREADS="$B300_STAGEH_FINAL_THREADS" \
 FORCED_BASE_BIN="$B300_STAGEH_CONTROL_BIN" FORCED_BASE_LABEL="$control_label" FORCED_BASE_THREADS="$B300_STAGEH_CONTROL_THREADS" \
 REBUILD_BUCKETS="$REBUILD_BUCKETS" SELECT_ONLY="$SELECT_ONLY" PREFIX="$RACE_PREFIX" "$ONEESAN_ROOT/scripts/run/b300x8-race-external-forced-profiled-once.sh" 27 "$@"
