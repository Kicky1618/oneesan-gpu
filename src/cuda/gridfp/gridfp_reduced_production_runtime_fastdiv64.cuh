__device__ __forceinline__ Rank64 runtime_owner_group_magic(
    int W, int outer_ones
) {
    return RP_RUNTIME_OWNER_GROUP_MAGIC[(W - RP_RUNTIME_OWNER_W_MIN) >> 1][outer_ones];
}

__device__ __forceinline__ Rank64 runtime_turn_compress_group_magic(
    int W, int outer_ones
) {
    return RP_RUNTIME_TURN_COMPRESS_GROUP_MAGIC[
        (W - RP_RUNTIME_OWNER_W_MIN) >> 1][outer_ones];
}

// For d>1, magic=ceil(2^64/d). Then floor(x*magic/2^64) is either
// floor(x/d) or exactly one larger. Detect the latter without division by
// examining the high word of q0*d and its low word versus x.
__device__ __forceinline__ void runtime_fastdivmod64_magic(
    Rank64 x,
    Rank64 divisor,
    Rank64 magic,
    Rank64& quotient,
    Rank64& remainder
) {
#if RP_RUNTIME_FAST_DIV64
    if (divisor == 1) {
        quotient = x;
        remainder = 0;
        return;
    }
    Rank64 q = __umul64hi(x, magic);
    const Rank64 product_lo = q * divisor;
    const Rank64 product_hi = __umul64hi(q, divisor);
    if (product_hi || product_lo > x) --q;
    quotient = q;
    remainder = x - q * divisor;
#else
    quotient = x / divisor;
    remainder = x % divisor;
#endif
}

